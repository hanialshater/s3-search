"""The Porter (1980) stemmer, written for the referee from the paper, so the reference scorer shares no code with the
engine (P6). It follows Snowball's `porter` definition: suffixes are matched longest first, and a word of any length is
stemmed (Snowball stems "gas" to "ga"; Porter's C version leaves words of two letters alone).

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

_VOWELS = frozenset("aeiou")


def _is_cons(w: str, i: int) -> bool:
    c = w[i]
    if c in _VOWELS:
        return False
    if c == "y":
        return i == 0 or not _is_cons(w, i - 1)
    return True


def _measure(stem: str) -> int:
    """m in [C](VC)^m[V]."""
    m, prev_vowel = 0, False
    for i in range(len(stem)):
        cons = _is_cons(stem, i)
        if cons and prev_vowel:
            m += 1
        prev_vowel = not cons
    return m


def _has_vowel(stem: str) -> bool:
    return any(not _is_cons(stem, i) for i in range(len(stem)))


def _double_cons(w: str) -> bool:
    return len(w) >= 2 and w[-1] == w[-2] and _is_cons(w, len(w) - 1)


def _cvc(w: str) -> bool:
    """*o: the stem ends consonant-vowel-consonant, and the last consonant is not w, x or y."""
    n = len(w)
    return (n >= 3 and _is_cons(w, n - 1) and not _is_cons(w, n - 2) and _is_cons(w, n - 3)
            and w[-1] not in "wxy")


def _replace(w: str, rules, cond) -> str:
    """Find the longest matching suffix; replace it if cond(stem) holds. Only that suffix is tried."""
    for suf, rep in rules:  # rules are sorted longest first
        if w.endswith(suf):
            stem = w[: len(w) - len(suf)]
            return stem + rep if cond(stem) else w
    return w


def _sorted(rules):
    return sorted(rules, key=lambda r: -len(r[0]))


_STEP2 = _sorted([
    ("ational", "ate"), ("tional", "tion"), ("enci", "ence"), ("anci", "ance"), ("izer", "ize"), ("abli", "able"),
    ("alli", "al"), ("entli", "ent"), ("eli", "e"), ("ousli", "ous"), ("ization", "ize"), ("ation", "ate"),
    ("ator", "ate"), ("alism", "al"), ("iveness", "ive"), ("fulness", "ful"), ("ousness", "ous"), ("aliti", "al"),
    ("iviti", "ive"), ("biliti", "ble")])
_STEP3 = _sorted([("icate", "ic"), ("ative", ""), ("alize", "al"), ("iciti", "ic"), ("ical", "ic"), ("ful", ""),
                  ("ness", "")])
_STEP4 = _sorted([(s, "") for s in ("al", "ance", "ence", "er", "ic", "able", "ible", "ant", "ement", "ment", "ent",
                                    "ion", "ou", "ism", "ate", "iti", "ous", "ive", "ize")])


def stem(w: str) -> str:
    # Step 1a
    if w.endswith("sses"):
        w = w[:-2]
    elif w.endswith("ies"):
        w = w[:-2]
    elif w.endswith("ss"):
        pass
    elif w.endswith("s"):
        w = w[:-1]
    # Step 1b
    if w.endswith("eed"):
        if _measure(w[:-3]) > 0:
            w = w[:-1]
    else:
        for suf in ("ing", "ed"):
            if w.endswith(suf):
                if _has_vowel(w[: -len(suf)]):
                    w = w[: -len(suf)]
                    if w.endswith(("at", "bl", "iz")):
                        w += "e"
                    elif _double_cons(w) and w[-1] not in "lsz":
                        w = w[:-1]
                    elif _measure(w) == 1 and _cvc(w):
                        w += "e"
                break
    # Step 1c
    if w.endswith("y") and _has_vowel(w[:-1]):
        w = w[:-1] + "i"
    # Steps 2 to 4
    w = _replace(w, _STEP2, lambda s: _measure(s) > 0)
    w = _replace(w, _STEP3, lambda s: _measure(s) > 0)
    for suf, _ in _STEP4:
        if w.endswith(suf):
            s = w[: len(w) - len(suf)]
            if _measure(s) > 1 and (suf != "ion" or s.endswith(("s", "t"))):
                w = s
            break
    # Step 5a
    if w.endswith("e"):
        s = w[:-1]
        m = _measure(s)
        if m > 1 or (m == 1 and not _cvc(s)):
            w = s
    # Step 5b
    if w.endswith("ll") and _measure(w[:-1]) > 1:
        w = w[:-1]
    return w
