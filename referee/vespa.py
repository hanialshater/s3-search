"""Vespa behind the engine's API (build_index, Index.search, Index.search_batch): the referee's quality adapter for the
competitor benchmarks (lab/benchmarks/fairness-rulings.md, Vespa V1 to V6), so `python -m referee full --engine=vespa`
scores Vespa with the same loader, test split and metrics as the engine, OpenSearch and zvec.

    S3_SEARCH_VESPA_URL=http://localhost:8090 [S3_SEARCH_VESPA_MODE=any|weakAnd] python -m referee full --engine=vespa ...

It talks to a running Vespa whose application is the platform-engineer's `colab/competitors/vespa_app` (schema
`product`, the `ids` document summary, rank profiles `title` and `bm25w`) and which already holds the catalogue.
`build_index` does not feed; it checks that the corpus is the catalogue: the document count must equal the catalogue's,
and a fixed sample of documents must hold the catalogue's text.

Requests map as follows:

- `match` on `product_title`: Vespa's `title` rank profile (bm25(product_title), k1 1.2, b 0.75) over that field;
- `multi_match` with fields `f^w`: the `bm25w` rank profile with `query(w_f)` = w for each named field and 0 for the
  others, matching only the named fields (one `userInput` per field, OR-ed), so a document that matches only an
  unnamed field is not returned with score 0;
- anything else is an `UnsupportedQuery`.

The match phase is `any` (a plain OR, every match ranked: exact, the headline) or `weakAnd` with targetHits = the
request's size (approximate, declared so), from `S3_SEARCH_VESPA_MODE`. Rank-property overrides for tuning come from
`S3_SEARCH_VESPA_RANK_PROPERTIES` (a JSON object sent as `ranking.properties`). V1: a response whose coverage is under
100% or that is degraded, or that carries errors, raises; it is never scored. Written by the evaluation-steward; makers
do not edit this file (P6).
"""
from __future__ import annotations

import json
import os
import random
import re
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor

FIELDS = ("product_title", "product_brand", "product_color", "product_bullet_point", "product_description")
_FIELD = re.compile(r"^([^\^]+)(?:\^([0-9.eE+-]+))?$")


class UnsupportedQuery(ValueError):
    def __init__(self, path, reason):
        super().__init__(f"{path}: {reason}")
        self.path, self.reason = path, reason


class InvalidRequest(UnsupportedQuery):
    pass


class Degraded(RuntimeError):
    """V1: Vespa answered with partial coverage, a degradation or errors."""


def url() -> str:
    return os.environ.get("S3_SEARCH_VESPA_URL", "http://localhost:8090").rstrip("/")


def mode() -> str:
    m = os.environ.get("S3_SEARCH_VESPA_MODE", "any")
    if m not in ("any", "weakAnd"):
        raise ValueError(f"S3_SEARCH_VESPA_MODE={m!r}: any or weakAnd")
    return m


def rank_properties() -> dict:
    raw = os.environ.get("S3_SEARCH_VESPA_RANK_PROPERTIES", "")
    return json.loads(raw) if raw else {}


def available_devices():
    return ["cpu"]


def _http(method: str, path: str, body=None, timeout=60):
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(url() + path, data=data, method=method, headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"{method} {path}: HTTP {e.code}: {e.read()[:500]!r}") from None


def settings() -> dict:
    out = {"url": url(), "mode": mode(), "rank_properties": rank_properties()}
    try:
        st = _http("GET", "/ApplicationStatus", timeout=10)
        out["version"] = st.get("application", {}).get("vespa", {}).get("version")
    except Exception:
        out["version"] = None
    return out


def _user_input(field: str, m: str, k: int) -> str:
    extra = f", targetHits: {k}" if m == "weakAnd" else ""
    return f'({{defaultIndex: "{field}", grammar: "{m}"{extra}}}userInput(@query))'


def body(request: dict) -> dict:
    """The /search/ body for an engine request; UnsupportedQuery for what this adapter does not map."""
    if not isinstance(request, dict) or not isinstance(request.get("query"), dict) or len(request["query"]) != 1:
        raise UnsupportedQuery("query", "one match or multi_match clause")
    k = int(request.get("size", 10))
    if k < 0:
        raise InvalidRequest("size", "a number >= 0")
    m = mode()
    (kind, b), = request["query"].items()
    if kind == "match":
        if not isinstance(b, dict) or len(b) != 1:
            raise UnsupportedQuery("query.match", "one field")
        (field, v), = b.items()
        if isinstance(v, dict):
            if set(v) - {"query"}:
                raise UnsupportedQuery(f"query.match.{field}", f"options {sorted(set(v) - {'query'})} are not mapped to Vespa")
            v = v.get("query")
        if field != "product_title":
            raise UnsupportedQuery(f"query.match.{field}", "only product_title has a single-field rank profile")
        out = {"yql": f"select * from product where {_user_input(field, m, k)}", "query": str(v), "hits": k,
               "ranking": "title", "presentation.summary": "ids", "timeout": "20s"}
    elif kind == "multi_match":
        if set(b) - {"query", "fields"}:
            raise UnsupportedQuery("query.multi_match", f"options {sorted(set(b) - {'query', 'fields'})} are not mapped to Vespa")
        weights = {}
        for f in b.get("fields") or []:
            mm = _FIELD.match(str(f))
            if not mm or mm.group(1) not in FIELDS:
                raise InvalidRequest("query.multi_match.fields", repr(f))
            weights[mm.group(1)] = float(mm.group(2) or 1.0)
        if not weights:
            raise UnsupportedQuery("query.multi_match.fields", "at least one field")
        where = " or ".join(_user_input(f, m, k) for f in weights)
        out = {"yql": f"select * from product where {where}", "query": str(b.get("query", "")), "hits": k,
               "ranking": "bm25w", "presentation.summary": "ids", "timeout": "20s"}
        for f in FIELDS:
            out[f"input.query(w_{f})"] = weights.get(f, 0.0)
    else:
        raise UnsupportedQuery(f"query.{kind}", "only match and multi_match are mapped to Vespa")
    rp = rank_properties()
    if rp:
        out["ranking.properties"] = rp
    return out


def convert(resp: dict, took_ms: float) -> dict:
    """V1 checked, then the engine's response shape."""
    root = resp.get("root", {})
    if root.get("errors"):
        raise Degraded(f"Vespa errors: {json.dumps(root['errors'])[:300]}")
    cov = root.get("coverage", {})
    if cov and (cov.get("coverage", 100) < 100 or cov.get("degraded") or not cov.get("full", True)):
        raise Degraded(f"Vespa coverage {json.dumps(cov)[:300]}")
    hits = [{"_id": str(c["fields"]["product_id"]), "_score": float(c.get("relevance", 0.0))}
            for c in root.get("children", []) if "fields" in c and "product_id" in c["fields"]]
    return {"hits": {"total": int(root.get("fields", {}).get("totalCount", len(hits))), "hits": hits},
            "took_ms": {"total": took_ms}}


def build_index(catalogue, mapping: dict, device: str = "cpu", sample: int = 50) -> "VespaIndex":
    if device != "cpu":
        raise ValueError(f"Vespa runs on cpu here, not {device!r}")
    idx = VespaIndex()
    n = idx.count()
    if n != len(catalogue):
        raise RuntimeError(f"Vespa holds {n} documents, the catalogue {len(catalogue)}: feed it first")
    rng = random.Random(20261114)
    ids = catalogue["product_id"].astype(str).tolist()
    titles = catalogue["product_title"].fillna("").astype(str).tolist()
    for i in rng.sample(range(len(ids)), min(sample, len(ids))):
        doc = _http("GET", f"/document/v1/esci/product/docid/{urllib.request.quote(ids[i], safe='')}", timeout=30)
        if doc.get("fields", {}).get("product_title", "") != titles[i]:
            raise RuntimeError(f"Vespa's document {ids[i]} does not hold the catalogue's title")
    return idx


class VespaIndex:
    threads = 8

    def count(self) -> int:
        r = _http("POST", "/search/", {"yql": "select * from product where true", "hits": 0, "timeout": "20s"})
        return int(r.get("root", {}).get("fields", {}).get("totalCount", -1))

    def search(self, request: dict) -> dict:
        b = body(request)
        t = time.perf_counter()
        resp = _http("POST", "/search/", b, timeout=30)
        return convert(resp, (time.perf_counter() - t) * 1e3)

    def search_batch(self, requests: list) -> list:
        with ThreadPoolExecutor(self.threads) as ex:
            return list(ex.map(self.search, requests))
