"""`python -m referee precision`: a lower-precision variant of the lexical path against the float64 path, on one index in
one process, judged against lab/benchmarks/precision-tolerance.md (the steward's gates, set before any run).

    python -m referee precision --variant=a:S3_TRITON_BM25_WEIGHTS=float16,S3_TRITON_BM25_SUM=float32 \\
        [--variant=b:S3_TRITON_BM25_SUM=float32 ...] [--k=2000] [--queries=N] [--out=precision.json]

All ESCI-US test queries (or the first N: development), the tuned BM25F request (bm25f-tuned.json and its .bm25 file) at
depth k. The baseline is the engine's default (no precision switch set). Each variant's switches are set in the
environment between calls on the same index; each variant runs twice (determinism); the contract runs on cuda with the
variant's switches set. Only the comparison figures leave this process: the per-query rankings and the test judgments
do not. Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

from referee import bench, loader, metrics

HERE = Path(__file__).resolve().parent
RECORD = 0.3039127040512092          # S1-7's score of record, 20bda25
GATES = {"ndcg10_vs_base": 0.0005, "ndcg10_vs_record": 0.0005, "recall_vs_base": 0.001, "top10_list_share": 0.05,
         "top10_set_share": 0.02, "ndcg10_moved_0.05_share": 0.005, "overlap_mean": 0.995, "overlap_floor": 0.95}
SWITCHES = ("S3_TRITON_BM25_WEIGHTS", "S3_TRITON_BM25_SUM", "S3_SEARCH_ACCUM")


def parse_variant(s: str) -> tuple[str, dict]:
    name, _, rest = s.partition(":")
    env = {}
    for kv in filter(None, rest.split(",")):
        k, _, v = kv.partition("=")
        if k not in SWITCHES:
            raise ValueError(f"{k}: not a precision switch ({', '.join(SWITCHES)})")
        env[k] = v
    if not name or not env:
        raise ValueError(f"{s!r}: name:SWITCH=value[,SWITCH=value]")
    return name, env


def compare(base: dict, var: dict, judg: dict, k: int) -> dict:
    """base, var: {query_id: (ids list, scores np.float64 array, total)}. The tolerance's figures and gates."""
    qids = sorted(judg)
    mb = metrics.score_run({q: base[q][0] for q in qids}, judg, 10, (1000, k))
    mv = metrics.score_run({q: var[q][0] for q in qids}, judg, 10, (1000, k))
    nb, nv = mb["mean"]["ndcg@10"], mv["mean"]["ndcg@10"]
    per_b = np.array([mb["per_query"][q]["ndcg@10"] or 0.0 for q in qids])
    per_v = np.array([mv["per_query"][q]["ndcg@10"] or 0.0 for q in qids])
    diff = per_v - per_b
    rng = np.random.default_rng(20261114)
    boots = np.array([diff[rng.integers(0, len(diff), len(diff))].mean() for _ in range(2000)]) if len(diff) else np.zeros(1)
    lists = sum(base[q][0][:10] != var[q][0][:10] for q in qids)
    sets = sum(set(base[q][0][:10]) != set(var[q][0][:10]) for q in qids)
    moved = int((np.abs(diff) > 0.05).sum())
    overlaps, low = [], []
    for q in qids:
        a, b = set(base[q][0][:k]), set(var[q][0][:k])
        n = max(len(a), len(b))
        ov = (len(a & b) / n) if n else 1.0
        overlaps.append(ov)
        if ov < GATES["overlap_floor"]:
            sc = base[q][1]
            tie = bool(len(sc) >= k and np.any(sc[:k - 1] == sc[k - 1])) if len(sc) else False
            low.append({"query_id": int(q), "overlap": round(ov, 4), "boundary_tie": tie})
    totals_differ = sum(base[q][2] != var[q][2] for q in qids)
    rel = []
    for q in qids:
        sb = dict(zip(base[q][0], base[q][1]))
        for i, s in zip(var[q][0], var[q][1]):
            if i in sb and sb[i] != 0:
                rel.append(abs(s - sb[i]) / abs(sb[i]))
    rel = np.array(rel) if rel else np.zeros(1)
    n = len(qids)
    rb, rv = mb["mean"], mv["mean"]
    fig = {
        "ndcg10_base": nb, "ndcg10_variant": nv, "ndcg10_diff": nv - nb,
        "ndcg10_diff_ci95": [float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))],
        "recall1000_base": rb["exact_recall@1000"], "recall1000_variant": rv["exact_recall@1000"],
        f"recall{k}_base": rb[f"exact_recall@{k}"], f"recall{k}_variant": rv[f"exact_recall@{k}"],
        "top10_list_changed_share": lists / n, "top10_set_changed_share": sets / n, "ndcg10_moved_0.05_share": moved / n,
        "overlap_mean": float(np.mean(overlaps)), "overlap_below_0.95": low[:200], "n_overlap_below_0.95": len(low),
        "queries_with_different_totals": int(totals_differ),
        "score_rel_error_max": float(rel.max()), "score_rel_error_p99": float(np.percentile(rel, 99)), "n_queries": n,
    }
    gates = {
        "1 ndcg10 within 0.0005 of float64": abs(nv - nb) <= GATES["ndcg10_vs_base"],
        "1 ndcg10 within 0.0005 of the record": abs(nv - RECORD) <= GATES["ndcg10_vs_record"],
        "2 recall@1000 within 0.001": abs(rv["exact_recall@1000"] - rb["exact_recall@1000"]) <= GATES["recall_vs_base"],
        f"2 recall@{k} within 0.001": abs(rv[f"exact_recall@{k}"] - rb[f"exact_recall@{k}"]) <= GATES["recall_vs_base"],
        "3 top 10 as a list changed in at most 5%": fig["top10_list_changed_share"] <= GATES["top10_list_share"],
        "3 top 10 as a set changed in at most 2%": fig["top10_set_changed_share"] <= GATES["top10_set_share"],
        "3 nDCG@10 moved over 0.05 in at most 0.5%": fig["ndcg10_moved_0.05_share"] <= GATES["ndcg10_moved_0.05_share"],
        f"4 mean top-{k} overlap at least 0.995": fig["overlap_mean"] >= GATES["overlap_mean"],
        "5 match counts equal": totals_differ == 0,
    }
    return {"figures": fig, "gates": gates}


def run_all(index, reqs: dict, env: dict, batch: int = 64) -> dict:
    saved = {s: os.environ.get(s) for s in SWITCHES}
    for s in SWITCHES:
        os.environ.pop(s, None)
    os.environ.update(env)
    try:
        out, qids = {}, list(reqs)
        for i in range(0, len(qids), batch):
            chunk = qids[i:i + batch]
            for q, r in zip(chunk, bench.api_search_batch(index, [reqs[q] for q in chunk])):
                hits = r["hits"]["hits"]
                out[q] = ([h["_id"] for h in hits], np.array([h["_score"] for h in hits], np.float64),
                          r["hits"]["total"] if not isinstance(r["hits"]["total"], dict) else r["hits"]["total"]["value"])
        return out
    finally:
        for s, v in saved.items():
            os.environ.pop(s, None) if v is None else os.environ.__setitem__(s, v)


def same_bits(a: dict, b: dict) -> bool:
    return all(a[q][0] == b[q][0] and np.array_equal(a[q][1].view(np.int64), b[q][1].view(np.int64)) and a[q][2] == b[q][2]
               for q in a)


def contract(env: dict, device: str) -> int:
    e = {**os.environ, **env, "S3_SEARCH_DEVICE": device}
    return subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", str(HERE / "contract")],
                          env=e, cwd=str(HERE.parent)).returncode


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m referee precision")
    ap.add_argument("--variant", action="append", required=True, help="name:SWITCH=value[,SWITCH=value]")
    ap.add_argument("--dataset", default="esci-us", choices=loader.DATASETS)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--k", type=int, default=2000)
    ap.add_argument("--queries", type=int, default=None, help="development: only the first N test queries")
    ap.add_argument("--skip-contract", action="store_true")
    ap.add_argument("--out", default="precision.json")
    a = ap.parse_args(argv)
    variants = [parse_variant(v) for v in a.variant]
    t0 = time.perf_counter()
    say = lambda m: print(f"[referee precision {time.perf_counter() - t0:7.1f} s] {m}", flush=True)
    api = bench.get_api("engine")
    ds = loader.load_dataset(a.dataset)
    judg = loader._load_dataset_test_judgments(a.dataset)      # the scorer, and only here
    queries = ds.test_queries if a.queries is None else ds.test_queries.iloc[: a.queries]
    judg = {int(q): judg[int(q)] for q in queries["query_id"] if int(q) in judg}
    m = copy.deepcopy(ds.mapping)
    m["_meta"]["engine"]["bm25"] = json.loads((HERE / "requests" / "bm25f-tuned.bm25.json").read_text())
    tmpl = json.loads((HERE / "requests" / "bm25f-tuned.json").read_text())
    reqs = {int(q): {**bench.fill(tmpl, str(t)), "size": a.k} for q, t in zip(queries["query_id"], queries["query"])}
    say(f"{len(ds.catalogue):,} products, {len(reqs):,} test queries, depth {a.k}, device {a.device}")
    index = api.build_index(ds.catalogue, m, device=a.device)
    say("index built")
    out = {"kind": "precision", "label": "development only (lab/benchmarks/precision-tolerance.md)", "commit": bench._rev(),
           "dataset": a.dataset, "device": a.device, "k": a.k, "n_queries": len(reqs),
           "development_mode": a.queries is not None, "engine_env": bench.engine_env(), "variants": {}}
    try:
        from engine.backend import get_backend
        from engine.backend.triton_gate import effective
        out["triton_effective"] = effective(get_backend(a.device))
    except Exception as e:                                   # noqa: BLE001
        out["triton_effective"] = f"unavailable: {e!r}"[:300]
    base = run_all(index, reqs, {})
    base2 = run_all(index, reqs, {})
    out["baseline_deterministic"] = same_bits(base, base2)
    mb = metrics.score_run({q: base[q][0] for q in judg}, judg, 10, (1000, a.k))["mean"]
    out["baseline"] = {"ndcg@10": mb["ndcg@10"], "exact_recall@1000": mb["exact_recall@1000"],
                       f"exact_recall@{a.k}": mb[f"exact_recall@{a.k}"], "equals_record": mb["ndcg@10"] == RECORD}
    say(f"baseline: nDCG@10 {mb['ndcg@10']!r} (record {RECORD!r}); deterministic {out['baseline_deterministic']}")
    ok_all = True
    for name, env in variants:
        v1 = run_all(index, reqs, env)
        v2 = run_all(index, reqs, env)
        res = compare(base, v1, judg, a.k)
        res["env"] = env
        res["gates"]["6 deterministic"] = same_bits(v1, v2)
        if a.skip_contract:
            res["contract_exit_code"] = None
        else:
            res["contract_exit_code"] = contract(env, a.device)
        # gate 7 is judged by the steward from the contract's output: a ranking check failing within gates 1 to 6 is the
        # expected consequence of a lower precision, any other failure fails the variant
        res["passed_gates_1_to_6"] = all(res["gates"].values())
        ok_all &= res["passed_gates_1_to_6"]
        out["variants"][name] = res
        f = res["figures"]
        say(f"{name} {env}: nDCG@10 {f['ndcg10_variant']:.10f} (diff {f['ndcg10_diff']:+.6f}), top-10 list changed "
            f"{f['top10_list_changed_share']:.4f}, overlap {f['overlap_mean']:.5f}, gates 1-6 {res['passed_gates_1_to_6']}, contract exit {res['contract_exit_code']}")
    Path(a.out).write_text(json.dumps(out, indent=1, default=str) + "\n")
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
