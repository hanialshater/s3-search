"""The referee's metrics, as the prototype computes them (baseline/esci_gpu_vs_opensearch.ipynb).

Whole-catalogue retrieval:

- An unjudged product in a result list counts as gain 0.
- The ideal DCG@10 is taken over the query's judged products.
- nDCG@10 is averaged over queries with a positive ideal.
- Exact recall@k is averaged over queries with at least one Exact product.

Gains follow the ESCI paper: E 1.0, S 0.1, C 0.01, I 0.0.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import numpy as np

GAIN = {"E": 1.0, "S": 0.1, "C": 0.01, "I": 0.0}


def discount(ranks: np.ndarray) -> np.ndarray:
    """1 / log2(rank + 2), rank counted from 0."""
    return 1.0 / np.log2(np.asarray(ranks, dtype=np.float64) + 2.0)


def score_query(ranked_ids, judgments: dict, k_ndcg: int = 10, recall_ks=(100, 1000)) -> dict:
    """Metrics for one query.

    ranked_ids: product ids in rank order. Negative ids are padding and are ignored.
    judgments: {product_id: "E" | "S" | "C" | "I"} for the query's judged products.
    """
    ranked = [p for p in ranked_ids if not (isinstance(p, (int, np.integer)) and p < 0)]
    gains = np.array([GAIN.get(judgments.get(p, ""), 0.0) for p in ranked[:k_ndcg]], dtype=np.float64)
    dcg = float((gains * discount(np.arange(len(gains)))).sum())
    ideal_gains = np.sort(np.array([GAIN[l] for l in judgments.values()], dtype=np.float64))[::-1][:k_ndcg]
    idcg = float((ideal_gains * discount(np.arange(len(ideal_gains)))).sum())
    out = {"ndcg@%d" % k_ndcg: (dcg / idcg) if idcg > 0 else None}
    exact = {p for p, l in judgments.items() if l == "E"}
    for k in recall_ks:
        out["exact_recall@%d" % k] = (len(exact.intersection(ranked[:k])) / len(exact)) if exact else None
    return out


def score_run(runs: dict, judgments: dict, k_ndcg: int = 10, recall_ks=(100, 1000)) -> dict:
    """Mean metrics over queries. runs: {query_id: ranked ids}; judgments: {query_id: {product_id: label}}.

    A query with no run counts as an empty result list (score 0), so a missing query can never raise the mean.
    """
    per = {q: score_query(runs.get(q, []), j, k_ndcg, recall_ks) for q, j in judgments.items()}
    keys = ["ndcg@%d" % k_ndcg] + ["exact_recall@%d" % k for k in recall_ks]
    means = {}
    for key in keys:
        vals = [m[key] for m in per.values() if m[key] is not None]
        means[key] = float(np.mean(vals)) if vals else None
        means["n_" + key] = len(vals)
    return {"mean": means, "per_query": per}
