"""The only way members read ESCI (Shakabuku Labs, search floor rule).

Members may use:
- the catalogue (products);
- the fit split (train-split judgments, to tune on);
- the test queries' texts and ids, with no judgments.

The test judgments are read only by the referee's scorer (`referee full`, run in Colab by the founder). ESCI is public,
so this boundary is a rule, not a secret: loading test judgments any other way breaks the floor's rules.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import copy
import hashlib
import json
import os
import urllib.request
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

BASE_URLS = ("https://github.com/amazon-science/esci-data/raw/main/shopping_queries_dataset/",
             "https://media.githubusercontent.com/media/amazon-science/esci-data/main/shopping_queries_dataset/")
PRODUCTS = "shopping_queries_dataset_products.parquet"
EXAMPLES = "shopping_queries_dataset_examples.parquet"
PRODUCT_COLS = ["product_id", "product_title", "product_brand", "product_color", "product_bullet_point",
                "product_description"]
DEFAULT_DIR = Path(os.environ.get("S3_SEARCH_DATA", "data/esci"))
SAMPLE_DIR = Path(os.environ.get("S3_SEARCH_SAMPLE", "data/esci-sample"))
DATASETS = ("toy", "esci-sample", "esci-us")

# esci-sample: the judged products of 2,000 train and 500 test queries (US, reduced set), drawn with a fixed seed.
SAMPLE_SEED = 20261109
SAMPLE_TRAIN, SAMPLE_TEST = 2000, 500
SAMPLE_MANIFEST = Path(__file__).resolve().parent.parent / "datasets" / "esci-sample.manifest.json"

TEXT_FIELDS = PRODUCT_COLS[1:]
# The mapping for esci-sample and esci-us (INTERFACES section 2). Lexical only: a member adds
# `_meta.engine.embeddings` (an encoder) to a copy of it for dense runs.
ESCI_MAPPING = {
    "_meta": {"engine": {"id_field": "product_id", "hot": [], "bm25": {"k1": 1.2, "b": 0.75}}},
    "properties": {
        "product_title": {"type": "text", "analyzer": "s3_english"},
        "product_brand": {"type": "text", "analyzer": "s3_english",
                          "fields": {"keyword": {"type": "keyword", "ignore_above": 256}}},
        "product_color": {"type": "text", "analyzer": "s3_english",
                          "fields": {"keyword": {"type": "keyword", "ignore_above": 256}}},
        "product_bullet_point": {"type": "text", "analyzer": "s3_english"},
        "product_description": {"type": "text", "analyzer": "s3_english"},
    }}


def _is_parquet(path: Path) -> bool:
    if not path.exists() or path.stat().st_size < 1024:
        return False
    with open(path, "rb") as f:
        head = f.read(4)
        f.seek(-4, os.SEEK_END)
        return head == b"PAR1" and f.read(4) == b"PAR1"


def fetch(data_dir: Path = DEFAULT_DIR) -> None:
    """Download the two ESCI files once. A failed Git LFS download leaves a small text file, which is refused."""
    data_dir = Path(data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    for name in (PRODUCTS, EXAMPLES):
        path = data_dir / name
        if _is_parquet(path):
            continue
        tmp = path.with_suffix(".tmp")
        for base in BASE_URLS:  # github.com/raw redirects to the LFS host; some networks allow only the LFS host
            try:
                urllib.request.urlretrieve(base + name, tmp)
            except OSError:
                continue
            if _is_parquet(tmp):
                tmp.replace(path)
                break
            tmp.unlink(missing_ok=True)
        else:
            raise IOError(f"{name}: no valid Parquet file from {', '.join(BASE_URLS)}")


def _examples(data_dir: Path, locale: str) -> pd.DataFrame:
    return pd.read_parquet(Path(data_dir) / EXAMPLES,
                           columns=["query_id", "query", "product_id", "esci_label", "split"],
                           filters=[("product_locale", "==", locale), ("small_version", "==", 1)])


def load_catalogue(data_dir: Path = DEFAULT_DIR, locale: str = "us") -> pd.DataFrame:
    return pd.read_parquet(Path(data_dir) / PRODUCTS, columns=PRODUCT_COLS,
                           filters=[("product_locale", "==", locale)])


def load_fit(data_dir: Path = DEFAULT_DIR, locale: str = "us") -> pd.DataFrame:
    """Train-split judgments: query_id, query, product_id, esci_label. Tune on these only."""
    ex = _examples(data_dir, locale)
    return ex[ex["split"] == "train"].drop(columns="split").reset_index(drop=True)


def load_test_queries(data_dir: Path = DEFAULT_DIR, locale: str = "us") -> pd.DataFrame:
    """The test queries to run, with no judgments: query_id, query."""
    ex = _examples(data_dir, locale)
    return ex[ex["split"] == "test"][["query_id", "query"]].drop_duplicates("query_id").reset_index(drop=True)


def _load_test_judgments(data_dir: Path = DEFAULT_DIR, locale: str = "us") -> dict:
    """{query_id: {product_id: label}}. The referee's scorer only."""
    ex = _examples(data_dir, locale)
    ex = ex[ex["split"] == "test"]
    out: dict = {}
    for q, p, l in zip(ex["query_id"], ex["product_id"], ex["esci_label"]):
        out.setdefault(int(q), {})[p] = l
    return out


# ---- Named datasets (B1-1, B1-2) ----------------------------------------------------------------------------------

@dataclass
class Dataset:
    """What a member may read: the catalogue, its mapping, the fit judgments and the test queries (no judgments)."""
    name: str
    catalogue: pd.DataFrame      # product_id + the five text columns (toy adds category, price, stock, embedding)
    mapping: dict                # an OpenSearch mapping body with `_meta.engine` (INTERFACES section 2)
    fit: pd.DataFrame            # query_id, query, product_id, esci_label (train split)
    test_queries: pd.DataFrame   # query_id, query


def _toy_all():
    from referee import toy
    cat = toy.build_catalogue()
    return cat, toy.build_judgments(cat)


def _dir_of(name: str) -> Path:
    return {"esci-sample": SAMPLE_DIR, "esci-us": DEFAULT_DIR}[name]


def available(name: str) -> bool:
    """Whether a dataset loads here without a download (toy always; esci-sample is built from the ESCI files)."""
    if name == "toy":
        return True
    raw = _is_parquet(DEFAULT_DIR / PRODUCTS) and _is_parquet(DEFAULT_DIR / EXAMPLES)
    return raw or (name == "esci-sample" and _sample_ready())


def load_dataset(name: str, build: bool = True) -> Dataset:
    """toy: built in memory (deterministic, a few ms). esci-sample: read from data/esci-sample, built from data/esci on
    first use if `build`. esci-us: the raw ESCI files in data/esci (see fetch())."""
    if name == "toy":
        from referee import toy
        cat, judg = _toy_all()
        cat.attrs = {}
        fit = judg[judg["split"] == "train"].drop(columns="split").reset_index(drop=True)
        tq = judg[judg["split"] == "test"][["query_id", "query"]].drop_duplicates("query_id").reset_index(drop=True)
        return Dataset("toy", cat, copy.deepcopy(toy.MAPPING), fit, tq)
    if name not in DATASETS:
        raise ValueError(f"unknown dataset {name!r}; one of {DATASETS}")
    if name == "esci-sample" and not _sample_ready() and build:
        build_esci_sample()
    d = _dir_of(name)
    cat = load_catalogue(d).reset_index(drop=True)
    return Dataset(name, cat, copy.deepcopy(ESCI_MAPPING), load_fit(d), load_test_queries(d))


def _load_dataset_test_judgments(name: str) -> dict:
    """{query_id: {product_id: label}} for a named dataset's test split. The referee's scorer only."""
    if name == "toy":
        _, judg = _toy_all()
        return _as_judgments(judg[judg["split"] == "test"])
    return _load_test_judgments(_dir_of(name))


def _as_judgments(frame: pd.DataFrame) -> dict:
    out: dict = {}
    for q, p, l in zip(frame["query_id"], frame["product_id"], frame["esci_label"]):
        out.setdefault(int(q), {})[p] = l
    return out


def fit_judgments(ds: Dataset) -> dict:
    """{query_id: {product_id: label}} for the fit split, which members may read."""
    return _as_judgments(ds.fit)


def _sample_ready(d: Path = None) -> bool:
    d = Path(d or SAMPLE_DIR)
    return _is_parquet(d / PRODUCTS) and _is_parquet(d / EXAMPLES)


def _content_hash(frame: pd.DataFrame, cols) -> str:
    h = hashlib.sha256()
    for c in cols:
        h.update(c.encode())
        h.update("\x1f".join(map(str, frame[c].tolist())).encode())
    return h.hexdigest()


def build_esci_sample(src: Path = None, out: Path = None, seed: int = SAMPLE_SEED, n_train: int = SAMPLE_TRAIN,
                      n_test: int = SAMPLE_TEST, locale: str = "us") -> dict:
    """Draw n_train train and n_test test queries (reduced set, one locale) with a fixed seed; keep every judgment of
    those queries and every product they judge. Written in ESCI's own schema, so the functions above read it as they
    read ESCI. Returns the manifest (counts and content hashes), also written next to the files."""
    src, out = Path(src or DEFAULT_DIR), Path(out or SAMPLE_DIR)
    if not (_is_parquet(src / PRODUCTS) and _is_parquet(src / EXAMPLES)):
        raise FileNotFoundError(f"esci-sample is built from the ESCI files in {src}; run referee.loader.fetch() first")
    ex = pd.read_parquet(src / EXAMPLES, filters=[("product_locale", "==", locale), ("small_version", "==", 1)])
    rng = np.random.default_rng(seed)
    picked = []
    for split, n in (("train", n_train), ("test", n_test)):
        ids = np.sort(ex.loc[ex["split"] == split, "query_id"].unique())
        picked.append(np.sort(rng.choice(ids, size=min(n, len(ids)), replace=False)))
    ex = ex[ex["query_id"].isin(np.concatenate(picked))]
    ex = ex.sort_values(["query_id", "product_id"], kind="stable").reset_index(drop=True)
    prod = pd.read_parquet(src / PRODUCTS, filters=[("product_locale", "==", locale)])
    prod = prod[prod["product_id"].isin(set(ex["product_id"]))]
    prod = prod.sort_values("product_id", kind="stable").reset_index(drop=True)
    out.mkdir(parents=True, exist_ok=True)
    for frame, name in ((prod, PRODUCTS), (ex, EXAMPLES)):
        tmp = out / (name + ".tmp")
        frame.to_parquet(tmp, index=False)
        tmp.replace(out / name)
    manifest = sample_manifest(prod, ex, seed)
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    return manifest


def sample_manifest(prod: pd.DataFrame, ex: pd.DataFrame, seed: int = SAMPLE_SEED) -> dict:
    """Counts and content hashes (independent of the parquet writer's version), so a rebuild can be checked."""
    by = ex.groupby("split")
    return {
        "seed": seed, "locale": "us", "small_version": 1,
        "queries": {s: int(g["query_id"].nunique()) for s, g in by},
        "judgments": {s: int(len(g)) for s, g in by},
        # Label counts for the fit split only: nothing about test judgments leaves the scorer, not even totals.
        "fit_labels": {k: int(v) for k, v in ex.loc[ex["split"] == "train", "esci_label"].value_counts().sort_index().items()},
        "products": int(len(prod)),
        "sha256": {"product_ids": _content_hash(prod, ["product_id"]),
                   "examples": _content_hash(ex, ["query_id", "product_id", "esci_label", "split"])},
    }
