"""The engine's contract (INTERFACES section 5), as plain check functions over the `toy` dataset.

`referee/contract/` runs them against `engine.api` on every device the engine reports; `referee/tests/` runs them
against the referee's own reference index, so the checks themselves are tested before the engine exists.

What each check compares with:
- lexical scores and order: the reference index (`referee/reference.py`), within SCORE_TOL; ties compared as groups;
- filters, facets, sort by a field and knn: brute force over the catalogue (pandas and numpy), exactly;
- pagination: the implementation's own single big page, exactly (from/size and search_after);
- errors: the named classes, with a `.path` naming the offending key.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from referee import reference

SCORE_TOL = 1e-4      # |engine - reference| <= SCORE_TOL * max(1, |reference|); engine scores are float32
DEVICE_RTOL = 1e-5    # between two devices of the engine (INTERFACES section 0)
ALL = 10_000          # a page large enough for every toy match


# ---- helpers -------------------------------------------------------------------------------------------------------

def _ids(resp):
    return [h["_id"] for h in resp["hits"]["hits"]]


def _close(a, b, tol=SCORE_TOL):
    return abs(float(a) - float(b)) <= tol * max(1.0, abs(float(b)))


def _groups(scores, tol=SCORE_TOL):
    """Tie groups: runs of consecutive (descending) scores within tol of their neighbour."""
    out, cur = [], [0]
    for i in range(1, len(scores)):
        if _close(scores[i], scores[i - 1], tol):
            cur.append(i)
        else:
            out.append(cur)
            cur = [i]
    if scores:
        out.append(cur)
    return out


def assert_same_ranking(got: dict, exp: dict, what: str, tol: float = SCORE_TOL):
    """Full result lists (every match) of a score-sorted request: same total, same scores per id, same order up to
    tie groups."""
    g, e = got["hits"]["hits"], exp["hits"]["hits"]
    assert got["hits"]["total"] == exp["hits"]["total"], f"{what}: total {got['hits']['total']} != {exp['hits']['total']}"
    assert len(g) == len(e), f"{what}: {len(g)} hits != {len(e)}"
    gids = [h["_id"] for h in g]
    assert len(set(gids)) == len(gids), f"{what}: duplicate ids"
    escore = {h["_id"]: h["_score"] for h in e}
    for i, h in enumerate(g):
        assert h["_id"] in escore, f"{what}: {h['_id']} is not a match"
        assert _close(h["_score"], escore[h["_id"]], tol), \
            f"{what}: {h['_id']} scored {h['_score']}, reference {escore[h['_id']]}"
        assert _close(h["_score"], e[i]["_score"], tol), f"{what}: rank {i} has score {h['_score']}, reference {e[i]['_score']}"
    for grp in _groups([h["_score"] for h in e], tol):
        assert {gids[i] for i in grp} == {e[i]["_id"] for i in grp}, f"{what}: tie group at rank {grp[0]} differs"


def _rows(ds, ids):
    pos = {p: i for i, p in enumerate(ds.catalogue["product_id"])}
    return [pos[i] for i in ids]


# ---- the requests --------------------------------------------------------------------------------------------------

FIELDS5 = ["product_title", "product_brand", "product_color", "product_bullet_point", "product_description"]
WEIGHTED = ["product_title^2", "product_brand^0.5", "product_color^0.7", "product_bullet_point^0.2",
            "product_description^0.3"]


def lexical_requests(ds):
    """Score-sorted requests over every toy query text: match, multi_match (BM25F) in several forms, bool."""
    out = []
    texts = list(dict.fromkeys(list(ds.fit["query"]) + list(ds.test_queries["query"])))
    texts += ["hiking", "drinks hot", "Kestrel's", "2-pack", "zzzz", "the and of"]
    for t in texts:
        out.append({"query": {"match": {"product_title": t}}})
        out.append({"query": {"multi_match": {"query": t, "fields": FIELDS5}}})
        out.append({"query": {"multi_match": {"query": t, "fields": WEIGHTED, "type": "cross_fields"}}})
    for t in texts[:10]:
        out.append({"query": {"multi_match": {"query": t, "fields": WEIGHTED, "operator": "and"}}})
        out.append({"query": {"multi_match": {"query": t, "fields": FIELDS5, "minimum_should_match": "50%"}}})
        out.append({"query": {"match": {"product_description": {"query": t, "boost": 2.5}}}})
        out.append({"query": {"bool": {"must": [{"match": {"product_title": t}}],
                                       "should": [{"match": {"product_bullet_point": "travel camping"}}]}}})
        out.append({"query": {"bool": {"should": [{"match": {"product_title": t}},
                                                  {"match": {"product_description": t}}],
                                       "minimum_should_match": 1, "boost": 0.5}}})
    for r in out:
        r["size"] = ALL
    return out


def filter_cases(ds):
    """(filter clauses, pandas mask over the catalogue) pairs."""
    c = ds.catalogue
    brand = c["product_brand"].astype(object)
    return [
        ([{"term": {"category": "mug"}}], c["category"] == "mug"),
        ([{"terms": {"category": ["boot", "tent"]}}], c["category"].isin(["boot", "tent"])),
        ([{"range": {"price": {"gte": 50, "lt": 120.5}}}], (c["price"] >= 50) & (c["price"] < 120.5)),
        ([{"range": {"price": {"gt": 250}}}], c["price"] > 250),
        ([{"term": {"stock": 0}}], c["stock"] == 0),
        ([{"range": {"stock": {"gte": 1, "lte": 30}}}], (c["stock"] >= 1) & (c["stock"] <= 30)),
        ([{"term": {"product_brand.keyword": "Acme"}}], brand == "Acme"),
        ([{"terms": {"product_color.keyword": ["red", "blue"]}}], c["product_color"].isin(["red", "blue"])),
        ([{"term": {"category": "lamp"}}, {"range": {"stock": {"gt": 0}}}], (c["category"] == "lamp") & (c["stock"] > 0)),
        ([{"bool": {"must_not": [{"term": {"category": "lamp"}}]}}], c["category"] != "lamp"),
        ([{"bool": {"should": [{"term": {"category": "lamp"}}, {"range": {"price": {"lt": 20}}}]}}],
         (c["category"] == "lamp") | (c["price"] < 20)),
        ([{"term": {"category": "no-such-category"}}], c["category"] == "no-such-category"),
    ]


# ---- the checks ----------------------------------------------------------------------------------------------------

def check_api_surface(api):
    assert callable(api.build_index) and callable(api.available_devices)
    devs = api.available_devices()
    assert devs and devs[0] == "cpu", f"available_devices() must start with 'cpu': {devs}"
    assert issubclass(api.UnsupportedQuery, ValueError)
    assert issubclass(api.InvalidRequest, api.UnsupportedQuery)


def check_lexical_scores(index, ds, ref):
    """BM25F and BM25 scores, totals and order against the reference, over every lexical request."""
    for r in lexical_requests(ds):
        assert_same_ranking(index.search(r), ref.search(r), json.dumps(r["query"]))


def check_lexical_formula_by_hand(index, ds):
    """One score worked from the interfaces' formula in this function, independent of the reference index."""
    from referee.analysis import analyze
    c = ds.catalogue
    toks = [analyze(t) for t in c["product_title"]]
    lens = np.array([len(t) for t in toks], dtype=float)
    avg, n, k1, b = lens.mean(), len(c), 1.2, 0.75
    term = analyze("lamp")[0]
    df = sum(term in t for t in toks)
    idf = np.log1p((n - df + 0.5) / (df + 0.5))
    tf = np.array([t.count(term) for t in toks], dtype=float)
    pseudo = tf / (1 - b + b * lens / avg)
    expect = np.where(tf > 0, idf * pseudo * (k1 + 1) / (k1 + pseudo), 0.0)
    resp = index.search({"query": {"match": {"product_title": "lamp"}}, "size": ALL})
    got = {h["_id"]: h["_score"] for h in resp["hits"]["hits"]}
    assert set(got) == set(c["product_id"][tf > 0]), "match product_title:lamp: wrong match set"
    for pid, s in zip(c["product_id"], expect):
        if s > 0:
            assert _close(got[pid], s), f"{pid}: {got[pid]} != {s} (BM25 by hand)"


def check_filters(index, ds):
    """Filters are exact: the match set equals a pandas mask over the catalogue, alone and under a scoring query."""
    ids = ds.catalogue["product_id"].to_numpy()
    for clauses, mask in filter_cases(ds):
        exp = set(ids[mask.to_numpy(dtype=bool)])
        r = index.search({"query": {"bool": {"filter": clauses}}, "size": ALL})
        assert set(_ids(r)) == exp and r["hits"]["total"] == len(exp), f"filter {clauses}"
        assert all(h["_score"] == 0.0 for h in r["hits"]["hits"]), f"filter {clauses}: filter-only scores must be 0"
        q = {"bool": {"must": [{"multi_match": {"query": "red waterproof lamp", "fields": FIELDS5}}], "filter": clauses}}
        r2 = index.search({"query": q, "size": ALL})
        free = index.search({"query": q["bool"]["must"][0], "size": ALL})
        fs = {h["_id"]: h["_score"] for h in free["hits"]["hits"]}
        assert set(_ids(r2)) == exp & set(fs), f"filter {clauses} under a query"
        for h in r2["hits"]["hits"]:
            assert _close(h["_score"], fs[h["_id"]]), f"filter {clauses}: a filter must not change the score"


def check_term_scores(index, ds):
    """term and terms alone score 1.0 (OpenSearch's constant score); match_all 1.0."""
    r = index.search({"query": {"term": {"category": "mug"}}, "size": ALL})
    assert r["hits"]["total"] == int((ds.catalogue["category"] == "mug").sum())
    assert all(h["_score"] == 1.0 for h in r["hits"]["hits"])
    r = index.search({"query": {"match_all": {}}, "size": 5})
    assert r["hits"]["total"] == len(ds.catalogue) and all(h["_score"] == 1.0 for h in r["hits"]["hits"])


def check_facets(index, ds):
    """terms aggregations count over the full match set (not the page), by count desc then key asc."""
    c = ds.catalogue
    queries = [None, {"multi_match": {"query": "waterproof boots", "fields": FIELDS5}},
               {"bool": {"filter": [{"range": {"price": {"lt": 100}}}]}}, {"term": {"category": "no-such"}}]
    for q in queries:
        for field, col, size in (("category", "category", 10), ("product_brand.keyword", "product_brand", 3),
                                 ("product_color.keyword", "product_color", 100), ("stock", "stock", 5)):
            req = {"size": 2, "aggs": {"f": {"terms": {"field": field, "size": size}}}}
            if q is not None:
                req["query"] = q
            r = index.search(req)
            allr = index.search({**{k: v for k, v in req.items() if k != "aggs"}, "size": ALL})
            rows = _rows(ds, _ids(allr))
            vals = c[col].iloc[rows].dropna()
            counts = sorted(vals.value_counts().items(), key=lambda kv: (-kv[1], kv[0]))
            exp = [{"key": (int(k) if col == "stock" else k), "doc_count": int(n)} for k, n in counts[:size]]
            got = r["aggregations"]["f"]["buckets"]
            assert [(b["key"], b["doc_count"]) for b in got] == [(b["key"], b["doc_count"]) for b in exp], \
                f"facet {field} under {q}: {got[:5]} != {exp[:5]}"
            other = int(sum(n for _, n in counts[size:]))
            assert r["aggregations"]["f"].get("sum_other_doc_count", other) == other, f"facet {field}: sum_other"
            assert len(r["hits"]["hits"]) <= 2 and r["hits"]["total"] == allr["hits"]["total"]


def _sort_requests():
    mm = {"multi_match": {"query": "red lamp waterproof boots", "fields": FIELDS5}}
    return [
        {"query": mm},                                                     # score, with exact ties (duplicates)
        {"query": {"match_all": {}}, "sort": [{"price": "asc"}]},           # price ties (duplicates) by doc id
        {"query": {"match_all": {}}, "sort": [{"price": {"order": "desc"}}]},
        {"query": mm, "sort": [{"category": "asc"}, "_score"]},
        {"query": {"bool": {"filter": [{"range": {"price": {"lt": 150}}}]}}, "sort": [{"stock": "desc"}, {"price": "asc"}]},
        {"query": {"match_all": {}}, "sort": [{"product_color.keyword": {"order": "asc", "missing": "_first"}}]},
        {"query": {"match_all": {}}, "sort": [{"product_brand.keyword": {"order": "desc", "missing": "_last"}}]},
    ]


def check_sort_by_field(index, ds):
    """Every hit carries `sort` ending with the doc id; field sorts equal a brute-force sort (ties by doc id)."""
    c = ds.catalogue.reset_index(drop=True)
    for req in _sort_requests():
        r = index.search({**req, "size": ALL})
        hits = r["hits"]["hits"]
        assert all(isinstance(h.get("sort"), list) and len(h["sort"]) >= 1 for h in hits), "every hit carries sort"
        if not req.get("sort") or any(e == "_score" or (isinstance(e, dict) and "_score" in e) for e in req["sort"]):
            continue
        parts = []
        for e in req["sort"]:
            (f, spec), = e.items()
            spec = {"order": spec} if isinstance(spec, str) else spec
            col = c[f.split(".")[0]]
            distinct = sorted({v for v in col if pd.notna(v)})
            rank = {v: i for i, v in enumerate(distinct)}
            sign = 1 if spec.get("order", "asc") == "asc" else -1
            miss = 1 if spec.get("missing", "_last") == "_last" else -1
            parts.append([(miss, 0) if pd.isna(v) else (0, sign * rank[v]) for v in col])
        rows = _rows(ds, _ids(r))
        exp = sorted(rows, key=lambda i: tuple(p[i] for p in parts) + (i,))
        exp = list(c["product_id"].iloc[exp])
        assert _ids(r) == exp, f"sort {req['sort']}: {_ids(r)[:8]} != {exp[:8]}"


def check_ties_by_doc_id(index, ds):
    """Exact duplicates in the toy catalogue score identically and come back in doc id (row) order."""
    c = ds.catalogue
    dup = c[c.duplicated(subset=["product_title", "product_description", "price"], keep=False)]
    assert len(dup) >= 4, "the toy catalogue must contain duplicates"
    for title in dup["product_title"].unique():
        r = index.search({"query": {"match": {"product_title": title}}, "size": ALL})
        same = [h for h in r["hits"]["hits"] if h["_id"] in set(dup[dup["product_title"] == title]["product_id"])]
        if len(same) > 1:
            assert len({h["_score"] for h in same}) == 1, f"duplicates of {title!r} scored differently"
            got = [h["_id"] for h in same]
            assert got == sorted(got, key=lambda p: _rows(ds, [p])[0]), f"ties for {title!r} not by doc id"


def check_pagination(index, ds):
    """from/size pages and a search_after walk both reproduce the single big page, with no duplicates or gaps."""
    for req in _sort_requests():
        big = index.search({**req, "size": ALL})
        exp = _ids(big)
        total = big["hits"]["total"]
        assert len(exp) == total and len(set(exp)) == total
        for size in (1, 7, 50):
            got = []
            for frm in range(0, total + size, size):
                page = index.search({**req, "from": frm, "size": size})
                assert page["hits"]["total"] == total
                got += _ids(page)
            assert got == exp, f"from/size {size} for {req}"
        for size in (7, 64):
            got, after = [], None
            for _ in range(total // size + 2):
                body = {**req, "size": size}
                if after is not None:
                    body["search_after"] = after
                page = index.search(body)["hits"]["hits"]
                if not page:
                    break
                got += [h["_id"] for h in page]
                after = page[-1]["sort"]
            assert got == exp, f"search_after {size} for {req}: {len(got)} of {len(exp)}"
        beyond = index.search({**req, "from": total, "size": 5})
        assert beyond["hits"]["hits"] == [] and beyond["hits"]["total"] == total


def check_knn(index, ds):
    """Exact knn: the brute-force top k by cosine, `_score = (1 + cos) / 2`, with and without a pre-filter."""
    c = ds.catalogue
    emb = np.stack(c["embedding"].to_numpy()).astype(np.float64)
    emb /= np.linalg.norm(emb, axis=1, keepdims=True)
    rng = np.random.default_rng(7)
    probes = [emb[5], emb[77], rng.normal(size=emb.shape[1])]
    for v in probes:
        v = np.asarray(v, dtype=np.float64)
        for k, filt, mask in ((10, None, np.ones(len(c), bool)),
                              (25, {"term": {"category": "mug"}}, (c["category"] == "mug").to_numpy()),
                              (5, {"range": {"price": {"lt": 60}}}, (c["price"] < 60).to_numpy())):
            spec = {"vector": [float(x) for x in v], "k": k}
            if filt is not None:
                spec["filter"] = filt
            r = index.search({"query": {"knn": {"embedding": spec}}, "size": k})
            sims = (1.0 + emb @ (v / np.linalg.norm(v))) / 2.0
            cand = np.flatnonzero(mask)
            top = cand[np.lexsort((cand, -sims[cand]))][:k]
            exp = [{"_id": c["product_id"].iat[i], "_score": sims[i]} for i in top]
            got = r["hits"]["hits"]
            assert len(got) == len(exp), f"knn k={k} filter={filt}: {len(got)} hits"
            for i, h in enumerate(got):
                assert mask[_rows(ds, [h["_id"]])[0]], f"knn: {h['_id']} breaks the filter"
                assert _close(h["_score"], sims[_rows(ds, [h["_id"]])[0]]), f"knn: {h['_id']} score"
                assert _close(h["_score"], exp[i]["_score"]), f"knn k={k}: rank {i}"
            for grp in _groups([e["_score"] for e in exp]):
                if grp[-1] < len(exp) - 1:  # the last group may be cut by k
                    assert {got[i]["_id"] for i in grp} == {exp[i]["_id"] for i in grp}, f"knn k={k}: tie group"


UNSUPPORTED = [
    ({"query": {"fuzzy": {"product_title": "lamp"}}}, "fuzzy"),
    ({"query": {"wildcard": {"product_title": "la*"}}}, "wildcard"),
    ({"query": {"query_string": {"query": "lamp"}}}, "query_string"),
    ({"query": {"bool": {"must": [{"match_phrase": {"product_title": "red lamp"}}]}}}, "match_phrase"),
    ({"query": {"match_all": {}}, "highlight": {"fields": {"product_title": {}}}}, "highlight"),
    ({"query": {"match_all": {}}, "aggs": {"h": {"histogram": {"field": "price", "interval": 10}}}}, "histogram"),
    ({"query": {"match_all": {}}, "collapse": {"field": "category"}}, "collapse"),
]
INVALID = [
    ({"query": {"match_all": {}}, "from": 9_995, "size": 10}, "from + size over 10,000"),
    ({"query": {"match_all": {}}, "size": "ten"}, "size not an int"),
]


def check_errors(index, api):
    """Anything outside the subset raises UnsupportedQuery naming its path; malformed requests raise InvalidRequest."""
    for req, key in UNSUPPORTED:
        try:
            index.search(req)
        except api.UnsupportedQuery as e:
            assert key in str(getattr(e, "path", "")), f"{key}: the error's path {getattr(e, 'path', None)!r}"
        else:
            raise AssertionError(f"{key}: no UnsupportedQuery")
    for req, what in INVALID:
        try:
            index.search(req)
        except api.InvalidRequest:
            pass
        else:
            raise AssertionError(f"{what}: no InvalidRequest")


def check_response_shape_and_determinism(index, ds):
    reqs = lexical_requests(ds)[:12] + _sort_requests()
    reqs = [{**r, "size": 10} for r in reqs]
    batch = index.search_batch(reqs)
    for r, b in zip(reqs, batch):
        one = index.search(r)
        again = index.search(r)
        assert _ids(one) == _ids(again) == _ids(b), f"not deterministic / batch differs: {r}"
        assert [h["_score"] for h in one["hits"]["hits"]] == [h["_score"] for h in again["hits"]["hits"]]
        assert all(_close(x["_score"], y["_score"]) for x, y in zip(one["hits"]["hits"], b["hits"]["hits"]))
        assert isinstance(one["hits"]["total"], int)
        tk = one["took_ms"]
        assert isinstance(tk, dict) and "total" in tk and all(float(v) >= 0 for v in tk.values())
        assert "aggregations" not in one, "aggregations only when requested"
    assert index.search_batch([]) == []


