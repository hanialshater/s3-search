"""`python -m referee bench`: quality, latency, throughput and cost of one implementation on one named dataset.

    python -m referee bench --dataset=toy|esci-sample|esci-us [--device=cpu] [--engine=engine|reference|opensearch]
                            [--request=template.json] [--k=100] [--batch=64] [--queries=N] [--out=results.json]

- Quality: whole-catalogue nDCG@10 and Exact recall@k (referee/metrics.py) on the **fit** split. The test split is
  scored only by `referee full` (the scorer), never here.
- Latency: page 1 (size 10) at batch 1, one `search` call at a time, wall clock: p50, p99, mean.
- Throughput: page 1 through `search_batch` in batches of --batch: queries per second.
- Cost per million queries: from --price-per-hour (the stated GPU and price), else null.
- The request: --request names a JSON template in which the string "{{query}}" is replaced by the query text; the
  default is BM25F over the five text fields with weight 1.

Numbers from a CPU device are labelled "development only": GPU numbers come only from the Colab referee.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import argparse
import importlib
import json
import os
import platform
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

from referee import loader
from referee.metrics import score_run

FIELDS5 = ["product_title", "product_brand", "product_color", "product_bullet_point", "product_description"]
DEFAULT_TEMPLATE = {"query": {"multi_match": {"query": "{{query}}", "fields": FIELDS5}}}
OPENSEARCH_TEMPLATE = {"query": {"multi_match": {"query": "{{query}}", "fields": FIELDS5, "type": "cross_fields"}}}
CPU_DEVICES = ("cpu", "torch-cpu")


def get_api(engine: str):
    """The implementation under test: `engine` (engine.api), `reference` (the referee's) or `opensearch`."""
    if engine == "engine":
        return importlib.import_module("engine.api")
    if engine == "reference":
        from referee import reference
        return reference
    if engine == "opensearch":
        from referee import opensearch
        return opensearch
    raise ValueError(f"unknown engine {engine!r}")


def fill(template, text: str):
    if isinstance(template, dict):
        return {k: fill(v, text) for k, v in template.items()}
    if isinstance(template, list):
        return [fill(v, text) for v in template]
    if isinstance(template, str):
        return text if template == "{{query}}" else template.replace("{{query}}", text)
    return template


def _pct(xs, q):
    return float(np.percentile(np.asarray(xs, dtype=np.float64), q)) if len(xs) else None


def _rev():
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                              cwd=Path(__file__).resolve().parent).stdout.strip() or None
    except OSError:
        return None


def run(ds, queries, judgments, api, device="cpu", template=None, k=100, batch=64, latency_queries=500,
        price_per_hour=None, split="fit", engine="engine", index=None, subsets=None, runs_out=None) -> dict:
    """Runs one benchmark. `queries` is a DataFrame[query_id, query]; `judgments` {query_id: {product_id: label}}.
    `subsets` ({name: set of query ids}) are scored from the same runs, e.g. the founder's held-out draw.
    `runs_out` (a dict), when given, receives the ranked ids per query that the quality numbers were computed from."""
    template = template or DEFAULT_TEMPLATE
    wall0 = time.perf_counter()
    if index is None:
        t = time.perf_counter()
        index = api.build_index(ds.catalogue, ds.mapping, device=device)
        build_s = time.perf_counter() - t
    else:
        build_s = None
    qids, texts = [int(q) for q in queries["query_id"]], [str(t) for t in queries["query"]]

    # Quality: k hits per query, batched.
    runs = {}
    for i in range(0, len(texts), batch):
        reqs = [{**fill(template, t), "size": k} for t in texts[i:i + batch]]
        for q, resp in zip(qids[i:i + batch], api_search_batch(index, reqs)):
            runs[q] = [h["_id"] for h in resp["hits"]["hits"]]
    if runs_out is not None:
        runs_out.update(runs)
    recall_ks = tuple(sorted({x for x in (k, 100, 1000) if x <= k}))
    quality = score_run(runs, judgments, k_ndcg=10, recall_ks=recall_ks)["mean"]
    quality_subsets = {name: score_run(runs, {q: j for q, j in judgments.items() if q in ids}, k_ndcg=10,
                                       recall_ks=recall_ks)["mean"] for name, ids in (subsets or {}).items()}

    # Latency: page 1 at batch 1.
    page1 = [{**fill(template, t), "size": 10} for t in texts]
    for r in page1[:5]:
        index.search(r)  # warm-up, not timed
    lat, stages = [], {}
    for r in page1[:latency_queries]:
        t = time.perf_counter()
        resp = index.search(r)
        lat.append((time.perf_counter() - t) * 1e3)
        for s, v in resp.get("took_ms", {}).items():
            stages.setdefault(s, []).append(float(v))

    # Throughput: page 1 through search_batch.
    t = time.perf_counter()
    for i in range(0, len(page1), batch):
        api_search_batch(index, page1[i:i + batch])
    tput_s = time.perf_counter() - t
    qps = len(page1) / tput_s if tput_s > 0 else None

    dev_only = device in CPU_DEVICES
    return {
        "kind": "bench", "label": "development only" if dev_only else "score candidate (GPU)",
        "dataset": ds.name, "split": split, "engine": engine, "device": device, "commit": _rev(),
        "created": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "host": {"cpus": os.cpu_count(), "machine": platform.machine(), "python": platform.python_version()},
        "n_queries": len(qids), "n_products": int(len(ds.catalogue)), "request_template": template,
        "quality": {k_: v for k_, v in quality.items()},
        **({"quality_subsets": quality_subsets} if subsets else {}),
        "latency_ms": {"batch": 1, "size": 10, "n": len(lat), "p50": _pct(lat, 50), "p99": _pct(lat, 99),
                       "mean": float(np.mean(lat)) if lat else None},
        "stage_ms_p50": {s: _pct(v, 50) for s, v in stages.items()},
        "throughput": {"batch": batch, "size": 10, "qps": qps},
        "cost_per_million_queries": (price_per_hour / 3600.0 * 1e6 / qps) if (price_per_hour and qps) else None,
        "price_per_hour": price_per_hour,
        "build_s": build_s, "wall_s": time.perf_counter() - wall0,
    }


def api_search_batch(index, reqs):
    out = index.search_batch(reqs)
    if len(out) != len(reqs):
        raise AssertionError(f"search_batch returned {len(out)} responses for {len(reqs)} requests")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m referee bench", description=__doc__.split("\n\n")[0])
    ap.add_argument("--dataset", default="toy", choices=loader.DATASETS)
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--engine", default="engine", choices=("engine", "reference", "opensearch"))
    ap.add_argument("--request", help="JSON request template with the string {{query}}")
    ap.add_argument("--k", type=int, default=100, help="hits per query for quality (Exact recall@k)")
    ap.add_argument("--batch", type=int, default=64)
    ap.add_argument("--queries", type=int, default=None, help="use only the first N fit queries")
    ap.add_argument("--latency-queries", type=int, default=500)
    ap.add_argument("--price-per-hour", type=float, default=None, help="the device's price, for cost per 1M queries")
    ap.add_argument("--out", default="results.json")
    a = ap.parse_args(argv)
    api = get_api(a.engine)
    ds = loader.load_dataset(a.dataset)
    queries = ds.fit[["query_id", "query"]].drop_duplicates("query_id").reset_index(drop=True)
    if a.queries:
        queries = queries.iloc[: a.queries]
    judg = loader.fit_judgments(ds)
    judg = {q: judg[q] for q in queries["query_id"]}
    template = json.loads(Path(a.request).read_text()) if a.request else \
        (OPENSEARCH_TEMPLATE if a.engine == "opensearch" else None)
    res = run(ds, queries, judg, api, device=a.device, template=template, k=a.k, batch=a.batch,
              latency_queries=a.latency_queries, price_per_hour=a.price_per_hour, engine=a.engine)
    Path(a.out).write_text(json.dumps(res, indent=1) + "\n")
    q, l = res["quality"], res["latency_ms"]
    print(f"bench {a.dataset} ({a.engine}, {a.device}; {res['label']}): {res['n_queries']} fit queries, "
          f"{res['n_products']} products")
    print(f"  nDCG@10 {q['ndcg@10']:.4f} | Exact recall@{a.k} {q[f'exact_recall@{a.k}']:.4f} | "
          f"p50 {l['p50']:.2f} ms, p99 {l['p99']:.2f} ms | {res['throughput']['qps']:.1f} QPS | "
          f"build {res['build_s']:.1f} s, wall {res['wall_s']:.1f} s -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
