"""The referee's reference index: an independent, plain implementation of the engine's API (INTERFACES sections 2, 4
and 5), written from the interfaces and the prototype's formulas, never from the engine's code (P6).

It is the oracle the contract compares the engine against (`referee/checks.py`), and a stand-in engine that lets the
referee test its own harnesses (bench, freshness, conformance) before the engine exists. It favours being obviously
right over being fast: scores in float64, brute force everywhere, no caching between requests.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import bisect
import math
import time
from collections import Counter

import numpy as np
import pandas as pd

from referee.analysis import analyze

MAX_WINDOW = 10_000


class UnsupportedQuery(ValueError):
    def __init__(self, path: str, reason: str):
        super().__init__(f"{path}: {reason}")
        self.path, self.reason = path, reason


class InvalidRequest(UnsupportedQuery):
    pass


class InvalidMapping(ValueError):
    pass


def available_devices() -> list:
    return ["cpu"]


def build_index(catalogue: pd.DataFrame, mapping: dict, device: str = "cpu") -> "ReferenceIndex":
    if device != "cpu":
        raise ValueError(f"the reference index runs on cpu only, not {device!r}")
    return ReferenceIndex(catalogue, mapping)


def _clauses(x):
    return [] if x is None else (list(x) if isinstance(x, list) else [x])


class ReferenceIndex:
    def __init__(self, catalogue: pd.DataFrame, mapping: dict):
        if not isinstance(mapping, dict) or not isinstance(mapping.get("properties"), dict):
            raise InvalidMapping("mapping.properties: missing")
        eng = mapping.get("_meta", {}).get("engine", {})
        self.mapping = mapping
        self.id_field = eng.get("id_field", "product_id")
        bm = eng.get("bm25", {})
        self.k1 = float(bm.get("k1", 1.2))
        raw_b = bm.get("b", 0.75)                 # a number, or a map of text field -> b (b_default for the rest)
        self.b = float(bm.get("b_default", 0.75)) if isinstance(raw_b, dict) else float(raw_b)
        self.field_b = {f: float(v) for f, v in raw_b.items()} if isinstance(raw_b, dict) else {}
        self.hot = set(eng.get("hot", []))
        self.ids = catalogue[self.id_field].astype(str).to_numpy(dtype=object)
        self.row_of = {d: i for i, d in enumerate(self.ids)}
        self.N = n = len(catalogue)
        self.version = 0
        self.live = np.ones(n, dtype=bool)
        self.text, self.keyword, self.numeric, self.ntype, self.vectors = {}, {}, {}, {}, {}
        for name, spec in mapping["properties"].items():
            t = spec.get("type")
            col = catalogue[name] if name in catalogue.columns else pd.Series([None] * n)
            if t == "text":
                self.text[name] = self._text_field(col)
                for sub, sspec in spec.get("fields", {}).items():
                    if sspec.get("type") == "keyword":
                        self.keyword[f"{name}.{sub}"] = self._keyword(col, sspec.get("ignore_above"))
            elif t == "keyword":
                self.keyword[name] = self._keyword(col, spec.get("ignore_above"))
            elif t in ("float", "double", "integer", "long", "boolean"):
                self.numeric[name] = pd.to_numeric(col.astype(object).where(col.notna(), np.nan),
                                                   errors="coerce").to_numpy(dtype=np.float64, copy=True)
                self.ntype[name] = t
            elif t == "knn_vector":
                if name in catalogue.columns:
                    m = np.stack([np.asarray(v, dtype=np.float64) for v in col])
                    norm = np.linalg.norm(m, axis=1, keepdims=True)
                    self.vectors[name] = m / np.where(norm > 0, norm, 1.0)
            else:
                raise InvalidMapping(f"mapping.properties.{name}.type: {t!r} is not supported")
        self.text_names = list(self.text)
        self._df_global = {}

    # ---- build -----------------------------------------------------------------------------------------------------
    def _text_field(self, col):
        lens = np.zeros(self.N, dtype=np.float64)
        post: dict = {}
        for i, v in enumerate(col.tolist()):
            toks = analyze(None if v is None or (isinstance(v, float) and math.isnan(v)) else v)
            lens[i] = len(toks)
            for t, c in Counter(toks).items():
                post.setdefault(t, ([], []))
                post[t][0].append(i)
                post[t][1].append(min(c, 255))  # the segment stores tf as uint8
        post = {t: (np.array(d, dtype=np.int64), np.array(c, dtype=np.float64)) for t, (d, c) in post.items()}
        avg = lens.mean() if self.N else 0.0
        return {"post": post, "len": lens, "avg": avg if avg > 0 else 1.0}

    def _keyword(self, col, ignore_above):
        vals = [None if (v is None or (isinstance(v, float) and math.isnan(v))) else str(v) for v in col.tolist()]
        if ignore_above:
            vals = [None if v is not None and len(v) > int(ignore_above) else v for v in vals]
        return np.array(vals, dtype=object)

    # ---- hot updates (the updater's calls, INTERFACES section 4) ------------------------------------------------------
    def patch(self, field, ids, values):
        if field not in self.hot or field not in self.numeric:
            raise ValueError(f"{field!r} is not a hot field")
        for d, v in zip(ids, values):
            self.numeric[field][self.row_of[d]] = np.nan if v is None else float(v)

    def delete(self, ids):
        for d in ids:
            if d in self.row_of:
                self.live[self.row_of[d]] = False

    def set_version(self, version):
        self.version = int(version)

    @property
    def n_docs(self):
        return self.N

    # ---- queries ---------------------------------------------------------------------------------------------------
    def _idf(self, df):
        return math.log1p((self.N - df + 0.5) / (df + 0.5))

    def _global_df(self, term):
        if term not in self._df_global:
            docs = [self.text[f]["post"][term][0] for f in self.text_names if term in self.text[f]["post"]]
            self._df_global[term] = len(np.unique(np.concatenate(docs))) if docs else 0
        return self._df_global[term]

    def _lexical(self, path, fields, text, operator="or", msm=None, boost=1.0, single_field_idf=False):
        for f, _ in fields:
            if f not in self.text:
                raise InvalidRequest(path, f"{f!r} is not a text field")
        terms = list(dict.fromkeys(analyze(text)))
        score = np.zeros(self.N)
        count = np.zeros(self.N, dtype=np.int64)
        for t in terms:
            pseudo = np.zeros(self.N)
            present = np.zeros(self.N, dtype=bool)
            for f, w in fields:
                fd = self.text[f]
                if t not in fd["post"]:
                    continue
                docs, tf = fd["post"][t]
                present[docs] = True
                bf = self.field_b.get(f, self.b)
                norm = np.maximum(1.0 - bf + bf * fd["len"][docs] / fd["avg"], 1e-6)
                pseudo[docs] += w * tf / norm
            if single_field_idf:
                p = self.text[fields[0][0]]["post"].get(t)
                df = 0 if p is None else len(p[0])
            else:
                df = self._global_df(t)
            idf = self._idf(df)
            score += np.where(pseudo > 0, idf * pseudo * (self.k1 + 1.0) / (self.k1 + np.maximum(pseudo, 1e-300)), 0.0)
            count += present
        need = len(terms) if operator == "and" else _msm(path, msm, len(terms), default=1)
        matched = (count >= max(need, 1)) if terms else np.zeros(self.N, dtype=bool)
        return matched, np.where(matched, score * boost, 0.0)

    def _field_values(self, path, field):
        if field in self.keyword:
            return "keyword", self.keyword[field]
        if field in self.numeric:
            return "numeric", self.numeric[field]
        raise InvalidRequest(path, f"{field!r} is not a keyword, numeric or boolean field")

    def _eq(self, path, field, values):
        kind, col = self._field_values(path, field)
        if kind == "keyword":
            return np.isin(col, [str(v) for v in values])
        nums = [float(v) for v in values]
        return np.isin(col, nums)

    def _node(self, path, q, scoring):
        """(matched bool[N], score float[N]) for one query clause."""
        if not isinstance(q, dict) or len(q) != 1:
            raise InvalidRequest(path, "a query clause is an object with exactly one key")
        (kind, body), = q.items()
        p = f"{path}.{kind}"
        if kind == "match_all":
            m = np.ones(self.N, dtype=bool)
            return m, np.full(self.N, float(body.get("boost", 1.0)) if scoring else 0.0)
        if kind == "match":
            (field, spec), = body.items()
            spec = spec if isinstance(spec, dict) else {"query": spec}
            _only(p + "." + field, spec, {"query", "operator", "minimum_should_match", "boost"})
            m, s = self._lexical(p, [(field, 1.0)], spec["query"], spec.get("operator", "or"),
                                 spec.get("minimum_should_match"), float(spec.get("boost", 1.0)), True)
            return m, s if scoring else np.zeros(self.N)
        if kind == "multi_match":
            _only(p, body, {"query", "fields", "type", "operator", "minimum_should_match", "tie_breaker", "boost"})
            if body.get("type", "best_fields") not in ("best_fields", "most_fields", "cross_fields"):
                raise UnsupportedQuery(p + ".type", f"{body.get('type')!r}")
            fields = []
            for f in body.get("fields") or []:
                name, _, w = f.partition("^")
                fields.append((name, float(w) if w else 1.0))
            if not fields:
                raise InvalidRequest(p + ".fields", "required")
            m, s = self._lexical(p, fields, body["query"], body.get("operator", "or"),
                                 body.get("minimum_should_match"), float(body.get("boost", 1.0)), len(fields) == 1)
            return m, s if scoring else np.zeros(self.N)
        if kind in ("term", "terms", "range"):
            (field, spec), = ((k, v) for k, v in body.items() if k != "boost")
            boost = float(body.get("boost", 1.0))
            if kind == "term":
                if isinstance(spec, dict):
                    boost = float(spec.get("boost", boost))
                    spec = spec["value"]
                m = self._eq(p, field, [spec])
            elif kind == "terms":
                if not isinstance(spec, list):  # a terms lookup ({"index", "id", "path"}) is outside the subset
                    raise UnsupportedQuery(f"{p}.{field}", "terms takes a list of values (no terms lookup)")
                m = self._eq(p, field, list(spec))
            else:
                _only(p + "." + field, spec, {"gte", "gt", "lte", "lt", "boost"})
                m = self._range(p, field, spec)
            return m, np.where(m, boost, 0.0) if scoring else np.zeros(self.N)
        if kind == "bool":
            return self._bool(p, body, scoring)
        if kind == "knn":
            (field, spec), = body.items()
            _only(p + "." + field, spec, {"vector", "k", "filter", "boost"})
            if field not in self.vectors:
                raise UnsupportedQuery(p + "." + field, "no vectors for this field")
            allow = self.live.copy()
            if spec.get("filter") is not None:
                allow &= self._node(p + "." + field + ".filter", spec["filter"], False)[0]
            v = np.asarray(spec["vector"], dtype=np.float64)
            v = v / (np.linalg.norm(v) or 1.0)
            sim = (1.0 + self.vectors[field] @ v) / 2.0
            cand = np.flatnonzero(allow)
            order = cand[np.lexsort((cand, -sim[cand]))][: int(spec["k"])]
            m = np.zeros(self.N, dtype=bool)
            m[order] = True
            return m, np.where(m, sim * float(spec.get("boost", 1.0)), 0.0) if scoring else np.zeros(self.N)
        raise UnsupportedQuery(p, f"query type {kind!r} is not in the subset")

    def _range(self, p, field, spec):
        kind, col = self._field_values(p, field)
        m = np.ones(self.N, dtype=bool)
        if kind == "keyword":
            present = np.array([v is not None for v in col])
            for op, v in spec.items():
                if op == "boost":
                    continue
                s = str(v)
                cmp = {"gte": lambda x: x >= s, "gt": lambda x: x > s, "lte": lambda x: x <= s,
                       "lt": lambda x: x < s}[op]
                m &= np.array([x is not None and cmp(x) for x in col])
            return m & present
        with np.errstate(invalid="ignore"):
            for op, v in spec.items():
                if op == "boost":
                    continue
                v = float(v)
                m &= {"gte": col >= v, "gt": col > v, "lte": col <= v, "lt": col < v}[op]
        return m & ~np.isnan(col)

    def _bool(self, p, body, scoring):
        _only(p, body, {"must", "should", "filter", "must_not", "minimum_should_match", "boost"})
        m = np.ones(self.N, dtype=bool)
        s = np.zeros(self.N)
        must, should = _clauses(body.get("must")), _clauses(body.get("should"))
        filt, must_not = _clauses(body.get("filter")), _clauses(body.get("must_not"))
        for i, c in enumerate(must):
            cm, cs = self._node(f"{p}.must[{i}]", c, scoring)
            m &= cm
            s += cs
        for i, c in enumerate(filt):
            m &= self._node(f"{p}.filter[{i}]", c, False)[0]
        for i, c in enumerate(must_not):
            m &= ~self._node(f"{p}.must_not[{i}]", c, False)[0]
        if should:
            cnt = np.zeros(self.N, dtype=np.int64)
            for i, c in enumerate(should):
                cm, cs = self._node(f"{p}.should[{i}]", c, scoring)
                cnt += cm
                s += np.where(cm, cs, 0.0)
            need = _msm(p + ".minimum_should_match", body.get("minimum_should_match"), len(should),
                        default=0 if (must or filt) else 1)
            m &= cnt >= need
        boost = float(body.get("boost", 1.0))
        return m, np.where(m, s * boost, 0.0)

    # ---- the request -----------------------------------------------------------------------------------------------
    def search(self, request: dict) -> dict:
        t0 = time.perf_counter()
        _only("", request, {"query", "aggs", "aggregations", "sort", "from", "size", "search_after", "explain",
                            "_source", "track_total_hits"})
        frm, size = request.get("from", 0), request.get("size", 10)
        if not isinstance(frm, int) or not isinstance(size, int) or frm < 0 or size < 0:
            raise InvalidRequest("from", "from and size are non-negative ints")
        if frm + size > MAX_WINDOW:
            raise InvalidRequest("size", f"from + size over {MAX_WINDOW}")
        after = request.get("search_after")
        if after is not None and frm != 0:
            raise InvalidRequest("search_after", "search_after needs from 0")
        q = request.get("query", {"match_all": {}})
        m, s = self._node("query", q, True)
        m &= self.live
        keys, specs = self._sort_keys("sort", request.get("sort"), s)
        rows = np.flatnonzero(m)
        order = rows[np.lexsort(tuple(k[rows] for k in reversed(keys + [np.arange(self.N, dtype=np.float64)])))]
        if after is not None:
            cursor = self._cursor("search_after", after, specs)
            tuples = [tuple(k[r] for k in keys) + (r,) for r in order]
            order = order[bisect.bisect_right(tuples, cursor):]
        page = order[frm: frm + size]
        hits = [{"_id": self.ids[r], "_score": float(s[r]),
                 "sort": [self._sort_value(sp, s, r) for sp in specs] + [int(r)]} for r in page]
        out = {"hits": {"total": int(m.sum()), "hits": hits}}
        aggs = request.get("aggs", request.get("aggregations"))
        if aggs is not None:
            out["aggregations"] = {name: self._agg(f"aggs.{name}", a, m) for name, a in aggs.items()}
        out["took_ms"] = {"total": (time.perf_counter() - t0) * 1e3}
        return out

    def search_batch(self, requests: list) -> list:
        return [self.search(r) for r in requests]

    def _sort_keys(self, path, sort, score):
        """Ascending numeric keys, one per sort entry, so lexsort gives the request's order; and the parsed specs."""
        sort = sort if sort is not None else ["_score"]
        sort = sort if isinstance(sort, list) else [sort]
        keys, specs = [], []
        for i, e in enumerate(sort):
            if isinstance(e, str):
                field, spec = e, {}
            elif isinstance(e, dict) and len(e) == 1:
                (field, spec), = e.items()
                spec = {"order": spec} if isinstance(spec, str) else dict(spec)
            else:
                raise InvalidRequest(f"{path}[{i}]", "a sort entry is a field name or {field: order}")
            order = spec.get("order", "desc" if field == "_score" else "asc")
            missing = spec.get("missing", "_last")
            if order not in ("asc", "desc") or missing not in ("_last", "_first"):
                raise InvalidRequest(f"{path}[{i}]", "order is asc|desc, missing is _last|_first")
            sign = -1.0 if order == "desc" else 1.0
            if field == "_score":
                keys.append(sign * score)
                specs.append(("_score", sign, missing, None))
                continue
            kind, col = self._field_values(f"{path}[{i}]", field)
            if kind == "keyword":
                values = sorted({v for v in col if v is not None})
                rank = {v: j for j, v in enumerate(values)}
                raw = np.array([np.nan if v is None else rank[v] for v in col], dtype=np.float64)
            else:
                values, raw = None, col.astype(np.float64)
            fill = math.inf if missing == "_last" else -math.inf
            keys.append(np.where(np.isnan(raw), fill, sign * raw))
            specs.append((field, sign, missing, values))
        return keys, specs

    def _sort_value(self, spec, score, r):
        field, _, _, values = spec
        if field == "_score":
            return float(score[r])
        kind, col = self._field_values("sort", field)
        v = col[r]
        if kind == "keyword":
            return v
        if v != v:
            return None
        return int(v) if self.ntype[field] in ("integer", "long") else (bool(v) if self.ntype[field] == "boolean"
                                                                         else float(v))

    def _cursor(self, path, after, specs):
        if not isinstance(after, list) or len(after) != len(specs) + 1:
            raise InvalidRequest(path, f"search_after has {len(specs) + 1} values: the sort keys, then the doc id")
        out = []
        for (field, sign, missing, values), v in zip(specs, after):
            if v is None:
                out.append(math.inf if missing == "_last" else -math.inf)
            elif values is not None:
                j = bisect.bisect_left(values, str(v))
                out.append(sign * (j if j < len(values) and values[j] == str(v) else j - 0.5))
            else:
                out.append(sign * float(v))
        return tuple(out) + (int(after[-1]),)

    def _agg(self, path, a, m):
        if isinstance(a, dict) and "aggs" in a or isinstance(a, dict) and "aggregations" in a:
            raise UnsupportedQuery(f"{path}.aggs", "sub-aggregations are outside the subset")
        if not isinstance(a, dict) or len(a) != 1:
            raise InvalidRequest(path, "an aggregation is an object with exactly one key")
        if list(a) != ["terms"]:
            raise UnsupportedQuery(f"{path}.{next(iter(a))}", "only terms aggregations are supported")
        spec = a["terms"]
        _only(path + ".terms", spec, {"field", "size"})
        kind, col = self._field_values(path + ".terms.field", spec["field"])
        size = int(spec.get("size", 10))
        vals = col[m]
        if kind == "keyword":
            c = Counter(v for v in vals if v is not None)
        else:
            t = self.ntype[spec["field"]]
            conv = int if t in ("integer", "long") else (bool if t == "boolean" else float)
            c = Counter(conv(v) for v in vals if v == v)
        ranked = sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))
        return {"buckets": [{"key": k, "doc_count": n} for k, n in ranked[:size]],
                "sum_other_doc_count": int(sum(n for _, n in ranked[size:]))}


def _only(path, body, allowed):
    if not isinstance(body, dict):
        raise InvalidRequest(path or "request", "expected an object")
    for k in body:
        if k not in allowed:
            raise UnsupportedQuery(f"{path}.{k}" if path else k, f"{k!r} is not supported here")


def _msm(path, msm, n, default):
    if msm is None:
        return default
    if isinstance(msm, int):
        return msm if msm >= 0 else max(n + msm, 0)
    if isinstance(msm, str) and msm.endswith("%"):
        pct = float(msm[:-1])
        return int(math.floor(n * pct / 100.0)) if pct >= 0 else n - int(math.floor(n * -pct / 100.0))
    if isinstance(msm, str) and msm.lstrip("-").isdigit():
        return _msm(path, int(msm), n, default)
    raise InvalidRequest(path, f"minimum_should_match {msm!r}")
