"""The referee's own `english` analyzer, as the prototype defines it (baseline notebook, section 2), which follows
Lucene's `english` analyzer: lowercase, words of letters and digits (with one inner apostrophe), possessive removal,
the 33 Lucene English stop words, Porter stemming.

The engine must analyse text the same way; the contract checks it on the toy catalogue.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import re
from functools import lru_cache

from referee.porter import stem

WORD = re.compile(r"[a-z0-9]+(?:'[a-z0-9]+)?")
EN_STOP = frozenset("a an and are as at be but by for if in into is it no not of on or such "
                    "that the their then there these they this to was will with".split())


@lru_cache(maxsize=None)
def _stem(w: str) -> str:
    return stem(w)


def analyze(text) -> list:
    if text is None:
        return []
    out = []
    for w in WORD.findall(str(text).lower()):
        if w.endswith("'s"):
            w = w[:-2]
        w = w.replace("'", "")
        if not w or w in EN_STOP:
            continue
        out.append(_stem(w))
    return out
