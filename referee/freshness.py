"""The freshness check (B1-4): hot-field changes, the time until each is visible, and equality with a rebuild.

    report = check_freshness(index, catalogue, mapping, apply=patch_hook(index), rebuild=api.build_index)

- `apply(changes)` is the path under test. Each change is {"_id": str, "fields": {hot field: value}}, the shape of a
  store `patch` record (INTERFACES section 3) without its offset. Today's hook is `patch_hook(index)`, which calls
  `Index.patch` directly (section 4); S2's is the data plane's: `store.apply(...)` then the replica's `poll()`.
- Visibility: after `apply` returns, the harness probes (a `terms` filter on the id field, sorted by the changed field)
  until every change in the batch shows its new value, and records each change's time to visible.
- Equality: the updated index and a fresh `rebuild` of the updated catalogue answer a probe set (filters, sorts and
  facets on the hot fields, and a lexical query under a filter) identically: ids and totals exactly, scores within
  the contract's tolerance.

The brief's run is 10,000 price and stock changes; the time to visible at p99 is the measure.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import time

import numpy as np
import pandas as pd

from referee import checks


def patch_hook(index):
    """Applies changes with Index.patch, one call per field per batch."""
    def apply(changes):
        by_field: dict = {}
        for c in changes:
            for f, v in c["fields"].items():
                by_field.setdefault(f, ([], []))
                by_field[f][0].append(c["_id"])
                by_field[f][1].append(v)
        for f, (ids, vals) in by_field.items():
            index.patch(f, ids, vals)
    return apply


def make_changes(catalogue, mapping, n, seed=20261110):
    """n changes to the hot fields, on random products; a product may change more than once."""
    eng = mapping["_meta"]["engine"]
    id_field, hot = eng["id_field"], list(eng.get("hot", []))
    if not hot:
        raise ValueError("the mapping names no hot fields (_meta.engine.hot)")
    rng = np.random.default_rng(seed)
    ids = catalogue[id_field].astype(str).to_numpy()
    out = []
    for _ in range(n):
        f = hot[int(rng.integers(len(hot)))]
        t = mapping["properties"][f]["type"]
        if t in ("integer", "long"):
            v = int(rng.integers(0, 100))
        elif t == "boolean":
            v = bool(rng.integers(2))
        else:
            v = round(float(rng.uniform(1, 500)), 2)
        out.append({"_id": str(ids[int(rng.integers(len(ids)))]), "fields": {f: v}})
    return out


def _probe(index, id_field, ids, field):
    r = index.search({"query": {"bool": {"filter": [{"terms": {id_field: ids}}]}}, "size": len(ids),
                      "sort": [{field: "asc"}]})
    return {h["_id"]: h["sort"][0] for h in r["hits"]["hits"]}


def _same(a, b):
    if a is None or b is None:
        return a is b
    return abs(float(a) - float(b)) <= 1e-6 * max(1.0, abs(float(b)))


def probe_requests(mapping):
    hot = list(mapping["_meta"]["engine"].get("hot", []))
    text = [f for f, s in mapping["properties"].items() if s.get("type") == "text"]
    out = []
    for f in hot:
        out += [{"query": {"bool": {"filter": [{"range": {f: {"gte": 10, "lt": 60}}}]}}, "sort": [{f: "asc"}]},
                {"query": {"match_all": {}}, "sort": [{f: {"order": "desc"}}]},
                {"query": {"match_all": {}}, "size": 0, "aggs": {"f": {"terms": {"field": f, "size": 20}}}}]
        if text:
            out.append({"query": {"bool": {"must": [{"multi_match": {"query": "red lamp", "fields": text}}],
                                           "filter": [{"range": {f: {"lte": 200}}}]}}})
    for r in out:
        r.setdefault("size", 500)
    return out


def check_freshness(index, catalogue: pd.DataFrame, mapping: dict, apply, rebuild, n_changes=10_000, batch=100,
                    timeout_s=60.0, seed=20261110, device="cpu") -> dict:
    eng = mapping["_meta"]["engine"]
    id_field = eng["id_field"]
    changes = make_changes(catalogue, mapping, n_changes, seed)
    vis_ms, failures = [], []
    for i in range(0, len(changes), batch):
        chunk = changes[i:i + batch]
        apply(chunk)
        t0 = time.perf_counter()
        want = {}
        for c in chunk:  # the last change to a product within the batch wins
            for f, v in c["fields"].items():
                want[(c["_id"], f)] = v
        pending = dict(want)
        while pending:
            seen_at = (time.perf_counter() - t0) * 1e3
            for f in {f for _, f in pending}:
                ids = sorted({d for d, g in pending if g == f})
                got = _probe(index, id_field, ids, f)
                for d in ids:
                    if d in got and _same(got[d], pending[(d, f)]):
                        vis_ms.append(seen_at)
                        del pending[(d, f)]
            if pending and time.perf_counter() - t0 > timeout_s:
                failures.append(f"{len(pending)} changes not visible after {timeout_s} s (batch at {i})")
                break
    # Equality with a rebuild of the updated catalogue.
    updated = catalogue.copy()
    row = {d: j for j, d in enumerate(updated[id_field].astype(str))}
    for c in changes:
        for f, v in c["fields"].items():
            updated.iat[row[c["_id"]], updated.columns.get_loc(f)] = v
    fresh = rebuild(updated, mapping, device=device)
    mismatches = []
    for r in probe_requests(mapping):
        a, b = index.search(r), fresh.search(r)
        try:
            assert a["hits"]["total"] == b["hits"]["total"], "total"
            assert [h["_id"] for h in a["hits"]["hits"]] == [h["_id"] for h in b["hits"]["hits"]], "ids"
            assert all(checks._close(x["_score"], y["_score"]) for x, y in zip(a["hits"]["hits"], b["hits"]["hits"]))
            assert a.get("aggregations") == b.get("aggregations"), "aggregations"
        except AssertionError as e:
            mismatches.append(f"{r}: {e}")
    return {
        "kind": "freshness", "n_changes": len(changes), "batch": batch, "visible": len(vis_ms),
        "visible_ms": {"p50": float(np.percentile(vis_ms, 50)) if vis_ms else None,
                       "p99": float(np.percentile(vis_ms, 99)) if vis_ms else None,
                       "max": float(max(vis_ms)) if vis_ms else None},
        "equal_to_rebuild": not mismatches, "mismatches": mismatches[:10], "failures": failures,
        "passed": not mismatches and not failures and len(vis_ms) > 0,
    }
