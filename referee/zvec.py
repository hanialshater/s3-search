"""zvec behind the engine's API (build_index, Index.search, Index.search_batch): the referee's quality adapter for the
competitor benchmarks (lab/benchmarks/fairness-rulings.md), so `python -m referee full --engine=zvec` scores zvec with
the same loader, the same test split and the same metrics as the engine and OpenSearch.

    pip install zvec==0.8.1
    S3_SEARCH_ZVEC_FUSION=weighted|rrf python -m referee full --engine=zvec --request=referee/requests/title-only.json

zvec (PyPI 0.8.1, Apache-2.0) is an in-process library with native full-text search scored by BM25 with fixed k1 and b.
It has one full-text field per query route, so this adapter maps the engine's requests onto it as follows:

- `match` on one field (`{"match": {"f": text}}` or `{"match": {"f": {"query": text}}}`): one route on that field;
- `multi_match` (`{"multi_match": {"query": text, "fields": ["f^w", ...]}}`): one route per field, fused by zvec's own
  re-ranker: `WeightedReRanker` with the request's field weights (the default) or `RrfReRanker()` (zvec's rank
  constant), chosen by `S3_SEARCH_ZVEC_FUSION`;
- anything else is an `UnsupportedQuery` naming what was asked.

The collection holds one full-text field per text field of the mapping, with zvec's documented English analysis
(tokenizer `standard`, filters `lowercase` and `stemmer`), missing values as empty strings, the mapping's id field as
the document id. It is built under `S3_SEARCH_ZVEC_DIR` and reused when its settings and document count match.
`settings()` gives what a results file records. Written by the evaluation-steward; makers do not edit this file (P6).
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import time
from pathlib import Path

PINNED = "0.8.1"
TOKENIZER, FILTERS = "standard", ("lowercase", "stemmer")
BATCH = 1024                                       # zvec's largest write batch
_INIT = False
_FIELD = re.compile(r"^([^\^]+)(?:\^([0-9.eE+-]+))?$")


class UnsupportedQuery(ValueError):
    def __init__(self, path, reason):
        super().__init__(f"{path}: {reason}")
        self.path, self.reason = path, reason


class InvalidRequest(UnsupportedQuery):
    pass


def available_devices():
    return ["cpu"]


def fusion() -> str:
    f = os.environ.get("S3_SEARCH_ZVEC_FUSION", "weighted")
    if f not in ("weighted", "rrf"):
        raise ValueError(f"S3_SEARCH_ZVEC_FUSION={f!r}: weighted or rrf")
    return f


def _zvec():
    import zvec
    return zvec


def settings() -> dict:
    """What a results file records about the zvec side."""
    out = {"pinned": PINNED, "fusion": fusion(), "tokenizer": TOKENIZER, "filters": list(FILTERS),
           "query_threads": int(os.environ.get("S3_SEARCH_ZVEC_QUERY_THREADS", "0")) or "zvec's default"}
    try:
        out["version"] = getattr(_zvec(), "__version__", None)
    except ImportError:
        out["version"] = None
    return out


def routes(request: dict):
    """(text, [(field, weight)], size) for a request this adapter supports; UnsupportedQuery otherwise."""
    if not isinstance(request, dict) or not isinstance(request.get("query"), dict) or len(request["query"]) != 1:
        raise UnsupportedQuery("query", "one match or multi_match clause")
    size = int(request.get("size", 10))
    if size < 0:
        raise InvalidRequest("size", "a number >= 0")
    (kind, body), = request["query"].items()
    if kind == "match":
        if not isinstance(body, dict) or len(body) != 1:
            raise UnsupportedQuery("query.match", "one field")
        (field, v), = body.items()
        if isinstance(v, dict):
            extra = set(v) - {"query"}
            if extra:
                raise UnsupportedQuery(f"query.match.{field}", f"options {sorted(extra)} are not mapped to zvec")
            v = v.get("query")
        return str(v), [(field, 1.0)], size
    if kind == "multi_match":
        extra = set(body) - {"query", "fields"}
        if extra:
            raise UnsupportedQuery("query.multi_match", f"options {sorted(extra)} are not mapped to zvec")
        fields = []
        for f in body.get("fields") or []:
            m = _FIELD.match(str(f))
            if not m:
                raise InvalidRequest("query.multi_match.fields", repr(f))
            fields.append((m.group(1), float(m.group(2) or 1.0)))
        if not fields:
            raise UnsupportedQuery("query.multi_match.fields", "at least one field")
        return str(body.get("query", "")), fields, size
    raise UnsupportedQuery(f"query.{kind}", "only match and multi_match are mapped to zvec")


def _text_fields(mapping: dict) -> list:
    return [f for f, sp in mapping.get("properties", {}).items() if isinstance(sp, dict) and sp.get("type") == "text"]


def build_index(catalogue, mapping: dict, device: str = "cpu", path: str | None = None) -> "ZvecIndex":
    if device != "cpu":
        raise ValueError(f"zvec runs on cpu here, not {device!r}")
    z = _zvec()
    fields = _text_fields(mapping)
    id_field = mapping.get("_meta", {}).get("engine", {}).get("id_field", "product_id")
    key = hashlib.md5(json.dumps([fields, id_field, TOKENIZER, FILTERS, len(catalogue), PINNED]).encode()).hexdigest()[:10]
    root = Path(path or os.environ.get("S3_SEARCH_ZVEC_DIR", "/content/zvec-referee")) / f"esci-{key}"
    stamp = root.with_suffix(".built")
    if not (root.exists() and stamp.exists()):
        shutil.rmtree(root, ignore_errors=True)
        root.parent.mkdir(parents=True, exist_ok=True)
        fts = z.FtsIndexParam(tokenizer_name=TOKENIZER, filters=list(FILTERS))
        schema = z.CollectionSchema(name="esci", fields=[
            z.FieldSchema(f, z.DataType.STRING, nullable=True, index_param=fts) for f in fields])
        col = z.create_and_open(path=str(root), schema=schema)
        ids = catalogue[id_field].astype(str).tolist()
        cols = {f: (catalogue[f].fillna("").astype(str).tolist() if f in catalogue.columns else [""] * len(ids))
                for f in fields}
        for k in range(0, len(ids), BATCH):
            col.insert([z.Doc(id=ids[i], fields={f: cols[f][i] for f in fields}) for i in range(k, min(k + BATCH, len(ids)))])
        col.optimize()
        if hasattr(col, "close"):
            col.close()
        stamp.write_text(json.dumps({"n_docs": len(ids), "fields": fields}))
    return ZvecIndex(str(root), fields)


class ZvecIndex:
    def __init__(self, path: str, fields: list):
        z = _zvec()
        global _INIT
        if not _INIT:                              # zvec.init configures the process once
            threads = int(os.environ.get("S3_SEARCH_ZVEC_QUERY_THREADS", "0"))
            z.init(query_threads=threads) if threads else z.init()
            _INIT = True
        self.col = z.open(path, option=z.CollectionOption(read_only=True))
        self.fields = set(fields)

    def search(self, request: dict) -> dict:
        z = _zvec()
        text, fields, size = routes(request)
        for f, _ in fields:
            if f not in self.fields:
                raise InvalidRequest("query", f"{f!r} is not a text field")
        t = time.perf_counter()
        qs = [z.Query(field_name=f, fts=z.Fts(match_string=text)) for f, _ in fields]
        if size == 0 or not text.strip():
            docs = []
        elif len(qs) == 1:
            docs = self.col.query(queries=qs[0], topk=size, output_fields=[])
        else:
            rr = z.RrfReRanker() if fusion() == "rrf" else z.WeightedReRanker([w for _, w in fields])
            docs = self.col.query(queries=qs, topk=size, output_fields=[], reranker=rr)
        hits = [{"_id": str(d.id), "_score": float(d.score)} for d in docs]
        return {"hits": {"total": len(hits), "hits": hits}, "took_ms": {"total": (time.perf_counter() - t) * 1e3}}

    def search_batch(self, requests: list) -> list:
        return [self.search(r) for r in requests]
