"""The `toy` dataset: a deterministic synthetic catalogue of 200 products and 30 judged queries, built in memory in a
few milliseconds, for the contract checks and for tests.

Its texts are made to exercise the analyzer (plurals, -ing forms, possessives, stop words, missing fields), and its
columns cover every type the contract needs: text (with keyword sub-fields), keyword, float, integer
(the hot field `stock`, often 0) and a 16-dimensional vector. Column names are ESCI's, as the interfaces (section 1) ask. Some products
are deliberate duplicates (same text, same price), so ties and their tie-break are tested.

Judgments follow the ESCI definitions:
- E: the product is the category asked for and has every attribute in the query;
- S: the right category, with an attribute that differs (a substitute);
- C: a complementary category (a mug for a kettle query, for example);
- I: anything else (5 sampled per query, as ESCI judges only some products).

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
