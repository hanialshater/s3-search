def _attributes(rng):
    rows = []
    for i in range(N_PRODUCTS):
        rows.append({"category": CATEGORIES[i % len(CATEGORIES)], "color": COLORS[rng.integers(len(COLORS))],
                     "material": MATERIALS[rng.integers(len(MATERIALS))],
                     "feature": FEATURES[rng.integers(len(FEATURES))], "brand": BRANDS[rng.integers(len(BRANDS))]})
    return rows


def build_catalogue() -> pd.DataFrame:
    rng = np.random.default_rng(SEED)
    attrs = _attributes(rng)
    cat_vec = rng.normal(size=(len(CATEGORIES), DIM))
    color_vec = rng.normal(size=(len(COLORS), DIM))
    rows = []
    for i, a in enumerate(attrs):
        cat = a["category"]
        noun = PLURAL[cat] if rng.random() < 0.3 else cat
        parts = [a["brand"]] * (rng.random() < 0.8) + [a["feature"]] * (rng.random() < 0.6) + \
                [a["color"]] * (rng.random() < 0.7) + [a["material"]] * (rng.random() < 0.5) + [noun]
        title = " ".join(parts)
        if rng.random() < 0.15:
            title += f", {int(rng.integers(1, 4))}-pack"
        bullets = " | ".join(BULLETS[j] for j in sorted(rng.choice(len(BULLETS), size=int(rng.integers(0, 4)),
                                                                     replace=False)))
        desc = TEMPLATES[int(rng.integers(len(TEMPLATES)))].format(**{**a, "category": noun})
        if rng.random() < 0.25:
            desc += f" Pairs well with a {COMPLEMENT[cat]}."
        emb = cat_vec[CATEGORIES.index(cat)] + 0.5 * color_vec[COLORS.index(a["color"])] + 0.3 * rng.normal(size=DIM)
        rows.append({
            "product_id": f"T{i:04d}", "product_title": title,
            "product_brand": a["brand"] if rng.random() < 0.9 else None,
            "product_color": a["color"] if rng.random() < 0.85 else None, "product_bullet_point": bullets or None,
            "product_description": desc if rng.random() < 0.95 else None,
            "category": cat, "price": round(float(rng.uniform(5, 300)), 2),
            "stock": int(rng.integers(0, 4) * rng.integers(0, 40)),
            "embedding": emb.astype(np.float32),
            "_attrs": a})
    # Deliberate exact duplicates of earlier products (new ids), so scores and prices tie.
    for k, src in enumerate((3, 17, 42, 42, 99, 150)):
        j = N_PRODUCTS - 1 - k
        rows[j] = {**rows[src], "product_id": f"T{j:04d}"}
    df = pd.DataFrame(rows)
    df.attrs["attributes"] = list(df.pop("_attrs"))
    return df


def _label(attrs: dict, cons: dict) -> str:
    if attrs["category"] == cons["category"]:
        return "E" if all(attrs[k] == v for k, v in cons.items()) else "S"
    if attrs["category"] == COMPLEMENT[cons["category"]]:
        return "C"
    return "I"


def build_judgments(catalogue: pd.DataFrame) -> pd.DataFrame:
    """All judgments, both splits: query_id, query, product_id, esci_label, split."""
    rng = np.random.default_rng(SEED + 1)
    test_ids = set(int(q) for q in rng.choice(np.arange(1, len(QUERIES) + 1), size=10, replace=False))
    rows = []
    attrs = catalogue.attrs["attributes"]
    ids = catalogue["product_id"].tolist()
    for qid, (text, cons) in enumerate(QUERIES, start=1):
        labels = [_label(a, cons) for a in attrs]
        irrelevant = [i for i, l in enumerate(labels) if l == "I"]
        keep_i = set(int(x) for x in rng.choice(irrelevant, size=5, replace=False))
        for i, l in enumerate(labels):
            if l != "I" or i in keep_i:
                rows.append({"query_id": qid, "query": text, "product_id": ids[i], "esci_label": l,
                             "split": "test" if qid in test_ids else "train"})
    return pd.DataFrame(rows)
