"""`python -m referee full`: the score of record (B1-6). Run by the founder in Colab on a GPU
(`referee/colab_referee.ipynb`); it writes results.json.

    python -m referee full [--dataset=esci-us] [--device=cuda] [--engine=engine|opensearch|zvec|vespa] [--request=template.json]
                           [--bm25=params.json] [--k=1000] [--price-per-hour=...] [--out=results.json]

The run records what it was asked to run: the request template and the --bm25 file (each with its sha256), the BM25
parameters the mapping carried, OpenSearch's version and analyzer, whether the checkout was clean, and its caveats.
The engine's score of record needs the contract run on the device (no --skip-contract) and a clean checkout.

1. The contract on this device: `referee/contract/` on toy (the notebook also runs `referee fast` first).
2. Quality on the **test** split: every test query, whole catalogue; nDCG@10 and Exact recall@k. This is the only
   place the test judgments are read (`loader._load_dataset_test_judgments`).
3. The same runs scored on the founder's held-out draw, when `S3_SEARCH_HELD_OUT` names its parquet (a `query_id`
   column; the lab's `lab/held-out/search-esci.md`). Members never see which queries it holds.
4. Latency at batch 1, throughput, cost per million queries (from the stated price).
5. Freshness: 10,000 hot-field changes through `Index.patch` on toy, on this device.

Each step prints a progress line with the elapsed time. **Development mode** (`--queries=N`: the first N test queries;
`--catalogue=sample`: ESCI-sample and its own test split) is labelled as such, sets `score_of_record` false and
writes `results-dev.json`; it refuses to write `results.json`. Only the full mode can be the score of record.

A land is accepted only if no gate falls and held-out nDCG@10 does not fall (the brief); comparing two results.json
files is the founder's step.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import pandas as pd

from referee import bench, freshness, loader, reference

HERE = Path(__file__).resolve().parent


def held_out_ids():
    path = os.environ.get("S3_SEARCH_HELD_OUT")
    if not path or not Path(path).exists():
        return None
    return set(int(q) for q in pd.read_parquet(path, columns=["query_id"])["query_id"])


def contract(device: str) -> int:
    """In its own process (474f9f5): the contract starts CUDA, and an index build after CUDA has started in this
    process must run single-process (forked workers can hang); the scored build then stays the first CUDA work here."""
    import subprocess
    env = {**os.environ, "S3_SEARCH_DEVICE": device}
    return subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", str(HERE / "contract")],
                          env=env, cwd=str(HERE.parent)).returncode


def tree_clean():
    """True when the checkout's tracked files equal its commit (untracked files, such as results, are ignored)."""
    import subprocess
    try:
        r = subprocess.run(["git", "diff", "--quiet", "HEAD", "--"], cwd=str(HERE.parent), capture_output=True)
    except OSError:
        return None
    return {0: True, 1: False}.get(r.returncode)


def build_mode() -> str:
    """Which way the engine's build will run, for the progress line (the score's definition does not depend on it)."""
    if os.environ.get("S3_BUILD_WORKERS"):
        return f"S3_BUILD_WORKERS={os.environ['S3_BUILD_WORKERS']} (set by the caller)"
    try:
        from engine.build import cuda_maybe_started
    except ImportError:
        return "unknown (engine.build has no cuda_maybe_started)"
    return ("serial: CUDA had already started in this process" if cuda_maybe_started()
            else "parallel workers: no CUDA work before the build")


def main(argv=None) -> int:
    import time
    ap = argparse.ArgumentParser(prog="python -m referee full")
    ap.add_argument("--dataset", default="esci-us", choices=loader.DATASETS)
    ap.add_argument("--engine", default="engine", choices=("engine", "opensearch", "reference", "zvec", "vespa"))
    ap.add_argument("--device", default=None, help="default: cuda if available, else cpu")
    ap.add_argument("--request", help="JSON request template with the string {{query}} (the engine's tuned request)")
    ap.add_argument("--bm25", help="JSON file of BM25F parameters for the engine's mapping (_meta.engine.bm25: k1, and b "
                                   "as a number or a per-field map with b_default), tuned on the fit split only; "
                                   "validated, recorded in the results with the file's sha256. engine or reference only")
    ap.add_argument("--k", type=int, default=1000)
    ap.add_argument("--batch", type=int, default=64)
    ap.add_argument("--latency-queries", type=int, default=1000)
    ap.add_argument("--price-per-hour", type=float, default=None)
    ap.add_argument("--skip-contract", action="store_true")
    ap.add_argument("--queries", type=int, default=None,
                    help="DEVELOPMENT MODE: only the first N test queries (never a score of record)")
    ap.add_argument("--catalogue", choices=("full", "sample"), default="full",
                    help="DEVELOPMENT MODE with 'sample': ESCI-sample and its own test split (never a score of record)")
    ap.add_argument("--out", default=None, help="default results.json; results-dev.json in development mode")
    a = ap.parse_args(argv)
    dev = a.queries is not None or a.catalogue == "sample"
    out_path = Path(a.out or ("results-dev.json" if dev else "results.json"))
    if dev and out_path.name == "results.json":
        print("referee full: development mode never writes results.json (the score of record's file); "
              "use --out=results-dev.json", file=sys.stderr)
        return 2
    dataset = "esci-sample" if a.catalogue == "sample" else a.dataset
    bm25 = None
    if a.bm25:
        # Steward's review of ba28176 (2026-11-13): the file only replaces _meta.engine.bm25 in the mapping the engine
        # builds from. It cannot reach the queries, the judgments, the metric or the held-out subset, which are fixed
        # by the dataset. It is validated (no unknown key: a typo would otherwise run the defaults while the results
        # recorded the typo'd values as applied; then the values, against the dataset's text fields, once loaded) and
        # recorded with its path and sha256.
        if a.engine == "opensearch":
            print("referee full: --bm25 sets the engine's BM25F; the OpenSearch adapter has one similarity per index "
                  "and does not take per-field b, so it does not apply to --engine=opensearch", file=sys.stderr)
            return 2
        if a.engine == "zvec":
            print("referee full: --bm25 sets the engine's BM25F; zvec's k1 and b are fixed, so it does not apply to "
                  "--engine=zvec", file=sys.stderr)
            return 2
        if a.engine == "vespa":
            print("referee full: --bm25 sets the engine's BM25F; Vespa's k1 and b are its rank profiles' (overridden with "
                  "S3_SEARCH_VESPA_RANK_PROPERTIES), so it does not apply to --engine=vespa", file=sys.stderr)
            return 2
        import hashlib
        raw = Path(a.bm25).read_bytes()
        params = json.loads(raw)
        if not isinstance(params, dict) or set(params) - set(reference.BM25_KEYS):
            bad = sorted(set(params) - set(reference.BM25_KEYS)) if isinstance(params, dict) else type(params).__name__
            print(f"referee full: --bm25={a.bm25}: an object with only {list(reference.BM25_KEYS)}, not {bad}",
                  file=sys.stderr)
            return 2
        bm25 = {"params": params, "file": {"path": a.bm25, "sha256": hashlib.sha256(raw).hexdigest()}}
    t0 = time.perf_counter()

    def say(msg):
        print(f"[referee full {time.perf_counter() - t0:7.1f} s] {msg}", flush=True)

    if dev:
        say("DEVELOPMENT MODE: " + ", ".join(x for x in (f"first {a.queries} test queries" if a.queries else "",
                                                          "ESCI-sample catalogue" if a.catalogue == "sample" else "") if x)
            + "; this run is not a score of record")
    api = bench.get_api(a.engine)
    devices = api.available_devices()        # torch.cuda.is_available(): does not start CUDA
    device = a.device or ("cuda" if "cuda" in devices else devices[0])
    out = {"kind": "full", "device": device, "devices": devices, "engine": a.engine}
    from referee import runtime
    out["runtime"] = runtime.environment()     # GPU, driver, CUDA, torch, RAPIDS (nvidia-smi and metadata: no CUDA)
    say(f"runtime: {out['runtime']['gpu']} (driver {out['runtime']['driver']}, CUDA {out['runtime']['cuda_driver_api']}, "
        f"torch CUDA {out['runtime']['torch_cuda']})")

    if a.skip_contract or a.engine != "engine":
        out["contract_exit_code"] = None
    else:
        say(f"contract: referee/contract on {device}")
        out["contract_exit_code"] = contract(device)
        say(f"contract: exit {out['contract_exit_code']}")

    say(f"data: loading {dataset}")
    ds = loader.load_dataset(dataset)
    judg = loader._load_dataset_test_judgments(dataset)       # the scorer, and only here
    queries = ds.test_queries
    if a.queries is not None:
        queries = queries.iloc[: a.queries]
        keep = set(int(q) for q in queries["query_id"])
        judg = {q: j for q, j in judg.items() if q in keep}
    say(f"data: {len(ds.catalogue):,} products, {len(queries):,} test queries")
    if bm25 is not None:
        import copy
        import dataclasses
        text_fields = [f for f, sp in ds.mapping.get("properties", {}).items() if sp.get("type") == "text"]
        try:
            reference.bm25_params(bm25["params"], text_fields)
        except reference.InvalidMapping as e:
            print(f"referee full: --bm25={a.bm25}: {e}", file=sys.stderr)
            return 2
        mapping = copy.deepcopy(ds.mapping)
        mapping.setdefault("_meta", {}).setdefault("engine", {})["bm25"] = bm25["params"]
        ds = dataclasses.replace(ds, mapping=mapping)
        out["bm25"] = bm25["params"]
        out["bm25_file"] = bm25["file"]
        say(f"bm25: {json.dumps(bm25['params'])}")
    # The BM25 parameters the run's mapping carries, with or without --bm25, so two results files always say them.
    out["bm25_effective"] = ds.mapping.get("_meta", {}).get("engine", {}).get("bm25", {})
    subsets = {}
    ho = held_out_ids()
    if ho is not None:
        subsets["held_out"] = ho & set(int(q) for q in queries["query_id"])
    template = json.loads(Path(a.request).read_text()) if a.request else \
        (bench.OPENSEARCH_TEMPLATE if a.engine == "opensearch" else None)
    if a.request:
        import hashlib
        out["request_file"] = {"path": a.request, "sha256": hashlib.sha256(Path(a.request).read_bytes()).hexdigest()}
    if a.engine == "opensearch":
        from referee import opensearch
        out["opensearch"] = {"analyzer": os.environ.get("S3_SEARCH_OS_ANALYZER") or "s3_english",
                             "version": opensearch.server_version()}
        say(f"opensearch: {out['opensearch']}")
    if a.engine == "zvec":
        from referee import zvec
        out["zvec"] = zvec.settings()
        say(f"zvec: {out['zvec']}")
    if a.engine == "vespa":
        from referee import vespa
        out["vespa"] = vespa.settings()
        say(f"vespa: {out['vespa']}")
    out["tree_clean"] = tree_clean()
    if a.engine == "engine":
        out["build_mode"] = build_mode()
        say(f"build: {out['build_mode']}")
    res = bench.run(ds, queries, judg, api, device=device, template=template, k=a.k, batch=a.batch,
                    latency_queries=a.latency_queries, price_per_hour=a.price_per_hour, split="test",
                    engine=a.engine, subsets=subsets, progress=say)
    out.update(res)
    out["kind"] = "full"
    out["held_out"] = None if ho is None else {"n_queries": len(subsets["held_out"])}
    # Steward, 2026-11-13: the engine's score of record needs the contract run on its device. The runs of dd319a7
    # with --skip-contract (bm25f-hand, bm25f-tuned) were marked score_of_record with the contract never run.
    skipped = a.engine == "engine" and out["contract_exit_code"] is None
    out["score_of_record"] = ((not dev) and device == "cuda" and dataset == "esci-us" and not skipped
                              and out["tree_clean"] is not False)
    caveats = []
    if ho is None:
        caveats.append("no held-out draw scored (S3_SEARCH_HELD_OUT unset or missing; ask L-7)")
    if skipped:
        caveats.append("the contract was skipped (--skip-contract): never a score of record")
    if out["tree_clean"] is False:
        caveats.append("tracked files differ from the commit: never a score of record")
    out["caveats"] = caveats
    if dev:
        out["label"] = "DEVELOPMENT MODE: not a score of record"
        out["development_mode"] = {"queries": a.queries, "catalogue": a.catalogue}
    elif out["score_of_record"] is False:
        out["label"] = "development only" + (": the contract was skipped" if skipped else "")

    if a.engine in ("engine", "reference"):
        say("freshness: 10,000 hot-field changes on toy")
        toy = loader.load_dataset("toy")
        idx = api.build_index(toy.catalogue, toy.mapping, device=device)
        if hasattr(idx, "patch"):
            out["freshness"] = freshness.check_freshness(idx, toy.catalogue, toy.mapping, freshness.patch_hook(idx),
                                                         api.build_index, n_changes=10_000, device=device)
        say(f"freshness: done (passed {out.get('freshness', {}).get('passed')})")
    gates = {"contract": out["contract_exit_code"] in (0, None),
             "freshness": out.get("freshness", {}).get("passed", True)}
    out["gates"] = gates
    out_path.write_text(json.dumps(out, indent=1, default=str) + "\n")
    q = out["quality"]
    say(f"done: {dataset} on {device} ({a.engine}): nDCG@10 {q['ndcg@10']:.4f}, "
        f"Exact recall@{a.k} {q.get(f'exact_recall@{a.k}')}, held-out "
        f"{out.get('quality_subsets', {}).get('held_out', {}).get('ndcg@10')}; "
        f"p50 {out['latency_ms']['p50']:.2f} ms, p99 {out['latency_ms']['p99']:.2f} ms; "
        f"{out['throughput']['qps']:.0f} QPS; gates {gates}; "
        f"{'NOT a score of record' if not out['score_of_record'] else 'score candidate'} -> {out_path}")
    return 0 if all(gates.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
