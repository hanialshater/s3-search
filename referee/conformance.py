"""The DSL conformance suite (B1-5; S3's predictions): 200 requests over `toy`, replayed against the engine and
compared with OpenSearch 2.19's recorded answers (or with the referee's reference index).

    python -m referee conformance [--engine=engine|reference] [--against=recorded|reference|opensearch] [--device=cpu]
    python -m referee conformance --record          # replay on a live OpenSearch and write the recording

**Suite v2** (evaluation-steward, 2026-11-10; replaces v1 before any judged run). Every request has a role:

- `p1` (160 requests): S3 prediction 1, "exact operators (filters, ranges, terms, facet counts, sort, from/size and
  search_after pages) return identical hits and counts to OpenSearch". Every p1 request has a total order that no
  lexical score decides (field sorts ending in `product_id`), or asks for counts only (size 0), so "identical" is
  exact: totals, aggregation buckets and the ordered hit ids must be equal. Families: `filter`, `filter_terms`,
  `sort`, `facets`, `page` (from/size), `search_after` (a walk of pages: each side passes its own last hit's `sort`
  back verbatim, as INTERFACES section 5 says; the concatenated ids are compared).
- `p2` (16 requests): S3 prediction 2, "a request the subset does not support is refused with a named error, never
  silently answered". Judged on the engine alone: it must raise `UnsupportedQuery` (or `InvalidRequest`). OpenSearch
  answers these; that is not a failure of anything.
- `info` (24 requests): lexical and knn scoring (`match`, `multi_match`, `bool_scored`, `knn`, `knn_filter`). Shown,
  never counted for prediction 1. **Lexical scores differ by design**: OpenSearch's BM25 uses the field's docCount
  for N, a per-field avgdl over documents that have the field, and one-byte field lengths, while the engine follows
  the prototype (`referee/lucene_model.py` reproduces OpenSearch's `match` scores to 1e-7). They are reported two
  ways: strict (scores within 1e-3 relative, ids equal outside tie groups) and as sets (the same hits).

v1 (2026-11-09) mixed lexical families into the OpenSearch rate and had no search_after family; its OpenSearch rate
(engine 144/183 strict, 183/183 as sets) was seen before v2 was written, and is reported as a baseline only.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
import sys
from pathlib import Path

import numpy as np

from referee import checks, loader

SUITE_VERSION = 2
N_REQUESTS = 200
F5 = checks.FIELDS5
OS_TOL = 1e-3   # info families, strict mode: relative score tolerance against OpenSearch
PLAN = [("filter", "p1", 30), ("filter_terms", "p1", 20), ("sort", "p1", 30), ("facets", "p1", 30),
        ("page", "p1", 30), ("search_after", "p1", 20),
        ("unsupported", "p2", 16),
        ("match", "info", 6), ("multi_match", "info", 6), ("bool_scored", "info", 4), ("knn", "info", 4),
        ("knn_filter", "info", 4)]
UNSUPPORTED = [
    {"query": {"fuzzy": {"product_title": "lamp"}}},
    {"query": {"match_phrase": {"product_title": "red lamp"}}},
    {"query": {"wildcard": {"product_title": "la*"}}},
    {"query": {"prefix": {"product_title": "lam"}}},
    {"query": {"regexp": {"product_title": "la.p"}}},
    {"query": {"query_string": {"query": "lamp AND red"}}},
    {"query": {"exists": {"field": "product_color"}}},
    {"query": {"match_all": {}}, "aggs": {"x": {"avg": {"field": "price"}}}},
    {"query": {"match_all": {}}, "aggs": {"h": {"histogram": {"field": "price", "interval": 50}}}},
    {"query": {"match_all": {}}, "highlight": {"fields": {"product_title": {}}}},
    {"query": {"match_all": {}}, "collapse": {"field": "category"}},
    {"query": {"function_score": {"query": {"match_all": {}}, "random_score": {}}}},
    {"query": {"match_all": {}}, "post_filter": {"term": {"category": "mug"}}},
    {"query": {"match_all": {}}, "aggs": {"c": {"cardinality": {"field": "category"}}}},
    {"query": {"multi_match": {"query": "red lamp", "fields": ["product_title"], "type": "phrase"}}},
    {"query": {"match_all": {}}, "script_fields": {"x": {"script": "1"}}},
]
TIE = {"product_id": "asc"}


def build_suite(ds=None, seed=20261110) -> list:
    """200 requests: [{"id", "family", "role", "request", "pages"?}], deterministic."""
    ds = ds or loader.load_dataset("toy")
    rng = np.random.default_rng(seed)
    texts = list(dict.fromkeys(list(ds.fit["query"]) + list(ds.test_queries["query"])))
    cats = sorted(ds.catalogue["category"].unique())
    brands = sorted(ds.catalogue["product_brand"].dropna().unique())
    emb = np.stack(ds.catalogue["embedding"].to_numpy())
    pick = lambda xs: xs[int(rng.integers(len(xs)))]  # noqa: E731
    lo = lambda: round(float(rng.uniform(5, 150)), 2)  # noqa: E731
    order = lambda: pick(["asc", "desc"])  # noqa: E731

    def filters():
        x = lo()
        return [{"terms": {"category": [str(c) for c in rng.choice(cats, int(rng.integers(1, 4)), replace=False)]}},
                {"range": {"price": {"gte": x, "lt": round(x + float(rng.uniform(30, 150)), 2)}}}]

    make = {
        "filter": lambda: {"query": {"bool": {"filter": filters()}}, "sort": [{"price": order()}, TIE], "size": 50},
        "filter_terms": lambda: {"query": {"bool": {"filter": [
            {"term": {"product_brand.keyword": pick(brands)}}, {"range": {"stock": {"gt": int(rng.integers(0, 20))}}}],
            "must_not": [{"term": {"category": pick(cats)}}]}}, "sort": [{"stock": order()}, TIE], "size": 50},
        "sort": lambda: {"query": {"bool": {"filter": [{"range": {"price": {"lt": lo() + 100}}}]}},
                         "sort": [{pick(["price", "stock", "category", "product_color.keyword"]): order()}, TIE],
                         "size": 40},
        "facets": lambda: {"query": pick([{"match": {pick(F5): pick(texts)}},
                                          {"bool": {"filter": filters()}}]), "size": 0, "aggs": {
            "c": {"terms": {"field": "category"}}, "b": {"terms": {"field": "product_brand.keyword", "size": 4}},
            "s": {"terms": {"field": "stock", "size": 5}}}},
        "page": lambda: {"query": {"bool": {"filter": [{"range": {"price": {"gte": lo()}}}]}},
                         "sort": [{"price": order()}, TIE], "from": int(rng.integers(0, 60)),
                         "size": int(rng.integers(1, 15))},
        "search_after": lambda: {"query": {"bool": {"filter": [{"range": {"price": {"lt": lo() + 120}}}]}},
                                 "sort": [{pick(["price", "stock"]): order()}, TIE],
                                 "size": int(rng.integers(3, 12))},
        "match": lambda: {"query": {"match": {pick(F5): pick(texts)}}},
        "multi_match": lambda: {"query": {"multi_match": {
            "query": pick(texts), "fields": [f"{f}^{w}" for f, w in zip(F5, rng.choice([0.2, 0.5, 1, 2], 5))],
            "type": pick(["best_fields", "most_fields", "cross_fields"])}}},
        "bool_scored": lambda: {"query": {"bool": {"must": [{"match": {"product_title": pick(texts)}}],
                                                   "should": [{"match": {"product_description": pick(texts)}}],
                                                   "must_not": [{"term": {"category": pick(cats)}}]}}},
        "knn": lambda: {"query": {"knn": {"embedding": {
            "vector": [round(float(x), 6) for x in emb[int(rng.integers(len(emb)))] + rng.normal(0, 0.2, emb.shape[1])],
            "k": int(rng.integers(3, 20))}}}, "size": 10},
        "knn_filter": lambda: {"query": {"knn": {"embedding": {
            "vector": [round(float(x), 6) for x in emb[int(rng.integers(len(emb)))]], "k": 10,
            "filter": {"term": {"category": pick(cats)}}}}}, "size": 10},
    }
    suite, i = [], 0
    for fam, role, n in PLAN:
        for j in range(n):
            s = {"id": i, "family": fam, "role": role,
                 "request": UNSUPPORTED[j % len(UNSUPPORTED)] if fam == "unsupported" else make[fam]()}
            if fam == "search_after":
                s["pages"] = int(rng.integers(3, 8))
            suite.append(s)
            i += 1
    assert len(suite) == N_REQUESTS
    return suite


def suite_sha256(suite) -> str:
    return hashlib.sha256(json.dumps([[s["request"], s.get("pages")] for s in suite], sort_keys=True).encode()
                          ).hexdigest()


# ---- running one suite entry against one implementation --------------------------------------------------------------

def outcome(index, s) -> dict:
    """{"ok": response} or {"error": class name}. A search_after entry is a walk: each page passes the implementation's
    own last-hit `sort` back; the result has the first page's total and the concatenated hits."""
    if hasattr(index, "recorded_outcome"):
        return index.recorded_outcome(s)
    try:
        if s["family"] != "search_after":
            return {"ok": index.search(s["request"])}
        hits, total, after = [], None, None
        for _ in range(s["pages"]):
            req = dict(s["request"])
            if after is not None:
                req["search_after"] = after
            r = index.search(req)
            total = r["hits"]["total"] if total is None else total
            page = r["hits"]["hits"]
            if not page:
                break
            hits += page
            after = page[-1]["sort"]
        return {"ok": {"hits": {"total": total, "hits": hits}}}
    except ValueError as e:  # UnsupportedQuery is a ValueError in every implementation
        return {"error": type(e).__name__, "reason": str(e)[:300]}


def _buckets(resp):
    return {k: v.get("buckets") for k, v in (resp.get("aggregations") or {}).items()}


def compare_exact(g, e) -> list:
    """p1: totals, aggregation buckets and the ordered hit ids, all exactly."""
    out = []
    if g["hits"]["total"] != e["hits"]["total"]:
        out.append(f"total {g['hits']['total']} != {e['hits']['total']}")
    if _buckets(g) != _buckets(e):
        out.append(f"aggregations differ: {_buckets(g)} vs {_buckets(e)}"[:240])
    gi, ei = [h["_id"] for h in g["hits"]["hits"]], [h["_id"] for h in e["hits"]["hits"]]
    if gi != ei:
        k = next((i for i, (a, b) in enumerate(zip(gi, ei)) if a != b), min(len(gi), len(ei)))
        out.append(f"ids differ from rank {k} ({len(gi)} vs {len(ei)} hits)")
    return out


def compare_scored(g, e, tol=OS_TOL, as_sets=False) -> list:
    """info: totals exactly; then either the same hit set, or per rank scores within tol and ids equal outside tie
    groups (a group cut by the page may show different members)."""
    out = [] if g["hits"]["total"] == e["hits"]["total"] else [f"total {g['hits']['total']} != {e['hits']['total']}"]
    gh, eh = g["hits"]["hits"], e["hits"]["hits"]
    gi, ei = [h["_id"] for h in gh], [h["_id"] for h in eh]
    if as_sets:
        return out + ([] if set(gi) == set(ei) else [f"{len(set(gi) ^ set(ei))} ids differ (as sets)"])
    if len(gi) != len(ei):
        return out + [f"{len(gi)} hits != {len(ei)}"]
    for i, (x, y) in enumerate(zip(gh, eh)):
        if not checks._close(x["_score"], y["_score"], tol):
            return out + [f"rank {i}: score {x['_score']} != {y['_score']}"]
    if gi != ei:
        for grp in checks._groups([h["_score"] for h in eh], tol):
            if {gi[i] for i in grp} != {ei[i] for i in grp} and grp[-1] != len(ei) - 1:
                return out + [f"ids differ at rank {grp[0]}"]
    return out


def judge(index, expected, suite) -> dict:
    """The engine (or reference) against `expected` (OpenSearch's recording, a live server, or the reference)."""
    rows = []
    for s in suite:
        g = outcome(index, s)
        row = {"id": s["id"], "family": s["family"], "role": s["role"]}
        if s["role"] == "p2":
            row["passed"] = g.get("error") in ("UnsupportedQuery", "InvalidRequest")
            row["diffs"] = [] if row["passed"] else [f"engine answered or raised {g.get('error')}"]
        else:
            e = outcome(expected, s)
            if "error" in g or "error" in e:
                row["diffs"] = [f"refused: engine {g.get('error')}, expected side {e.get('error')}"]
                row["passed"] = False
                row["passed_as_sets"] = False
            elif s["role"] == "p1":
                row["diffs"] = compare_exact(g["ok"], e["ok"])
                row["passed"] = not row["diffs"]
            else:
                row["diffs"] = compare_scored(g["ok"], e["ok"])
                row["passed"] = not row["diffs"]
                row["passed_as_sets"] = not compare_scored(g["ok"], e["ok"], as_sets=True)
        rows.append(row)

    def rate(rs, key="passed"):
        return {"passed": sum(bool(r.get(key)) for r in rs), "n": len(rs),
                "rate": (sum(bool(r.get(key)) for r in rs) / len(rs)) if rs else None}

    fams = {}
    for fam, role, _ in PLAN:
        rs = [r for r in rows if r["family"] == fam]
        fams[fam] = {"role": role, **rate(rs)}
        if role == "info":
            fams[fam]["as_sets"] = rate(rs, "passed_as_sets")
    p1 = [r for r in rows if r["role"] == "p1"]
    p2 = [r for r in rows if r["role"] == "p2"]
    return {"kind": "conformance", "suite_version": SUITE_VERSION, "suite_sha256": suite_sha256(suite),
            "expected": getattr(expected, "meta", {"implementation": type(expected).__name__}),
            "p1": rate(p1), "p2": rate(p2), "by_family": fams,
            "failures": [r for r in rows if not r["passed"]][:60]}


# ---- recordings of OpenSearch's answers -------------------------------------------------------------------------------

RECORDING = Path(__file__).resolve().parent / "conformance" / f"opensearch-2.19-toy-v{SUITE_VERSION}.jsonl.gz"


def record(os_index, suite, path=RECORDING, meta=None) -> Path:
    """Replay the suite against OpenSearch; one JSON line per entry (gzip), with the run's took times removed."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(path, "wt", encoding="utf-8") as fh:
        fh.write(json.dumps({"meta": {**(meta or {}), "suite_version": SUITE_VERSION,
                                      "suite_sha256": suite_sha256(suite)}}) + "\n")
        for s in suite:
            o = outcome(os_index, s)
            if "ok" in o:
                o["ok"].pop("took_ms", None)
            fh.write(json.dumps({"id": s["id"], "family": s["family"], **o}, sort_keys=True) + "\n")
    return path


class Recorded:
    """OpenSearch's recorded answers, by suite entry."""

    def __init__(self, suite, path=RECORDING):
        with gzip.open(path, "rt", encoding="utf-8") as fh:
            lines = [json.loads(x) for x in fh if x.strip()]
        self.meta = lines[0]["meta"]
        if self.meta["suite_sha256"] != suite_sha256(suite):
            raise ValueError("the recording is of a different suite")
        self._by_id = {x["id"]: x for x in lines[1:]}

    def recorded_outcome(self, s):
        x = self._by_id[s["id"]]
        return {k: v for k, v in x.items() if k in ("ok", "error", "reason")}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m referee conformance")
    ap.add_argument("--engine", default="engine", choices=("engine", "reference"))
    ap.add_argument("--against", default="recorded", choices=("recorded", "reference", "opensearch"))
    ap.add_argument("--record", action="store_true", help="replay the suite on a live OpenSearch and write the recording")
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--out", default="results/conformance.json")
    a = ap.parse_args(argv)
    from referee.bench import get_api
    ds = loader.load_dataset("toy")
    suite = build_suite(ds)
    if a.record:
        from referee import opensearch
        p = record(opensearch.build_index(ds.catalogue, ds.mapping), suite,
                   meta={"server": "OpenSearch 2.19.1 (Lucene 9.12.1), single node, one shard", "dataset": "toy",
                         "analyzer": os.environ.get("S3_SEARCH_OS_ANALYZER") or "s3_english (referee/opensearch.py)"})
        print(f"recorded {len(suite)} answers -> {p}")
        return 0
    index = get_api(a.engine).build_index(ds.catalogue, ds.mapping, device=a.device)
    if a.against == "recorded":
        expected = Recorded(suite)
    else:
        expected = get_api(a.against).build_index(ds.catalogue, ds.mapping, device="cpu")
        expected.meta = {"implementation": a.against, "live": True}
    rep = judge(index, expected, suite)
    rep.update({"engine": a.engine, "device": a.device, "against": a.against})
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(rep, indent=1, default=str) + "\n")
    print(f"conformance v{SUITE_VERSION} ({a.engine} on {a.device} vs {a.against}): prediction 1 (exact operators) "
          f"{rep['p1']['passed']}/{rep['p1']['n']}; prediction 2 (refused) {rep['p2']['passed']}/{rep['p2']['n']} "
          f"-> {a.out}")
    for fam, f in rep["by_family"].items():
        extra = f"; as sets {f['as_sets']['passed']}/{f['as_sets']['n']}" if "as_sets" in f else ""
        print(f"  {fam:13s} {f['role']:4s} {f['passed']}/{f['n']}{extra}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
