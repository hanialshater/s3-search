"""OpenSearch behind the engine's API (build_index, Index.search, Index.search_batch), so the benchmark and the
conformance suite run the matched baseline the same way they run the engine. Standard library only (urllib).

    S3_SEARCH_OPENSEARCH_URL=http://localhost:9200 python -m referee bench --dataset=esci-us --engine=opensearch

The index uses the mapping as given (OpenSearch stores `_meta` and ignores it) and defines `s3_english` as the
prototype's analyzer: a pattern tokenizer on [a-z0-9'], lowercase, possessive removal, the 33 Lucene English stop
words, Porter stemming. `bm25` in `_meta.engine` becomes the index's default BM25 similarity.

Run in Colab next to a local OpenSearch (as the prototype did). Not run in CI: no OpenSearch there.

Owner: evaluation-steward. Makers do not edit this file (P6).
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import time
import urllib.error
import urllib.request

import pandas as pd

from referee.analysis import EN_STOP

URL = os.environ.get("S3_SEARCH_OPENSEARCH_URL", "http://localhost:9200")


class UnsupportedQuery(ValueError):
    def __init__(self, path, reason):
        super().__init__(f"{path}: {reason}")
        self.path, self.reason = path, reason


class InvalidRequest(UnsupportedQuery):
    pass


def server_version():
    """OpenSearch's version number, for the results file; None if it does not answer."""
    try:
        return _call("GET", "/").get("version", {}).get("number")
    except Exception:
        return None


def available_devices():
    return ["cpu"]


def _call(method, path, body=None, ndjson=False):
    data = None
    headers = {}
    if body is not None:
        data = body.encode() if isinstance(body, str) else json.dumps(body).encode()
        headers["Content-Type"] = "application/x-ndjson" if ndjson else "application/json"
    req = urllib.request.Request(URL + path, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=600) as r:
            return json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        detail = e.read().decode(errors="replace")[:500]
        if e.code == 400:
            raise UnsupportedQuery("opensearch", detail) from None
        raise


def _with_analyzer(mapping, name):
    """S3_SEARCH_OS_ANALYZER=english swaps s3_english for OpenSearch's built-in `english`, as the prototype indexed."""
    m = json.loads(json.dumps(mapping))
    for spec in m["properties"].values():
        if spec.get("analyzer") == "s3_english":
            spec["analyzer"] = name
    return m


def index_settings(mapping):
    if os.environ.get("S3_SEARCH_OS_ANALYZER"):
        mapping = _with_analyzer(mapping, os.environ["S3_SEARCH_OS_ANALYZER"])
    bm = mapping.get("_meta", {}).get("engine", {}).get("bm25", {})
    if isinstance(bm.get("b"), dict):
        # One BM25 similarity per index here; a per-field b map would be sent to OpenSearch as an object.
        raise UnsupportedQuery("_meta.engine.bm25.b", "a per-field b map is not mapped to OpenSearch similarities")
    return {"settings": {
        "number_of_shards": 1, "number_of_replicas": 0, "index.knn": True,
        "index.translog.flush_threshold_size": "64mb",  # a small translog: the shared disk is tight
        "similarity": {"default": {"type": "BM25", "k1": bm.get("k1", 1.2), "b": bm.get("b", 0.75)}},
        "analysis": {
            "tokenizer": {"s3_words": {"type": "pattern", "pattern": "[a-z0-9]+(?:'[a-z0-9]+)?", "group": 0,
                                       "flags": "CASE_INSENSITIVE"}},
            "filter": {"s3_stop": {"type": "stop", "stopwords": sorted(EN_STOP)},
                       "s3_possessive": {"type": "stemmer", "language": "possessive_english"},
                       "s3_apostrophe": {"type": "pattern_replace", "pattern": "'", "replacement": ""},
                       # Snowball's Porter, as INTERFACES section 2 names (snowballstemmer "porter"). Lucene's
                       # porter_stem differs: it leaves words of one or two letters alone (xs, us), Snowball does
                       # not. Until 2026-11-10 this was porter_stem; S7-9's first run found it.
                       "s3_porter": {"type": "snowball", "language": "Porter"}},
            "analyzer": {"s3_english": {"type": "custom", "tokenizer": "s3_words",
                                        "filter": ["lowercase", "s3_possessive", "s3_apostrophe", "s3_stop",
                                                   "s3_porter"]}}}},
        "mappings": mapping}


def build_index(catalogue: pd.DataFrame, mapping: dict, device: str = "cpu", name: str | None = None):
    id_field = mapping.get("_meta", {}).get("engine", {}).get("id_field", "product_id")
    # The name covers the whole index body (mapping, analyzer, similarity) and the catalogue size, so a changed
    # analyzer never reuses an index built with the old one.
    name = name or "s3ref-" + hashlib.md5(json.dumps([index_settings(mapping), len(catalogue)], sort_keys=True,
                                                     default=str).encode()).hexdigest()[:10]
    try:
        n = _call("GET", f"/{name}/_count").get("count")
    except urllib.error.HTTPError:
        n = None
    if n != len(catalogue):
        try:
            _call("DELETE", f"/{name}")
        except urllib.error.HTTPError:
            pass
        _call("PUT", f"/{name}", index_settings(mapping))
        fields = [f for f in mapping["properties"] if f in catalogue.columns]
        recs = catalogue[fields].to_dict("records")
        for i in range(0, len(recs), 5000):
            lines = []
            for r in recs[i:i + 5000]:
                doc = {k: _clean(v) for k, v in r.items()}
                lines.append(json.dumps({"index": {"_index": name, "_id": str(r[id_field])}}))
                lines.append(json.dumps(doc))
            _call("POST", "/_bulk", "\n".join(lines) + "\n", ndjson=True)
        _call("POST", f"/{name}/_refresh")
    return OpenSearchIndex(name)


def _clean(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return None
    if hasattr(v, "tolist"):
        return v.tolist()
    return v.item() if hasattr(v, "item") else v


def _convert(resp, took_ms):
    hits = resp["hits"]
    total = hits["total"]["value"] if isinstance(hits["total"], dict) else hits["total"]
    out = {"hits": {"total": int(total), "hits": [
        {"_id": h["_id"], "_score": h.get("_score"), **({"sort": h["sort"]} if "sort" in h else {}),
         **({"highlight": h["highlight"]} if "highlight" in h else {})}
        for h in hits["hits"]]}, "took_ms": {"total": took_ms, "opensearch": float(resp.get("took", 0))}}
    if "aggregations" in resp:
        out["aggregations"] = {k: _agg(v) for k, v in resp["aggregations"].items()}
    return out


def _agg(v):
    """An aggregation as OpenSearch gives it, with `key_as_string` dropped from buckets and sub-aggregations kept;
    terms aggregations keep `sum_other_doc_count` (0 when absent)."""
    if not isinstance(v, dict) or "buckets" not in v:
        return v
    buckets = []
    for b in v["buckets"]:
        nb = {k: (_agg(x) if isinstance(x, dict) else x) for k, x in b.items() if k != "key_as_string"}
        buckets.append(nb)
    out = {"buckets": buckets}
    if "sum_other_doc_count" in v or "doc_count_error_upper_bound" in v:
        out["sum_other_doc_count"] = v.get("sum_other_doc_count", 0)
    return out


class OpenSearchIndex:
    def __init__(self, name):
        self.name = name

    def search(self, request: dict) -> dict:
        body = {"track_total_hits": True, **request}
        t = time.perf_counter()
        resp = _call("POST", f"/{self.name}/_search", body)
        return _convert(resp, (time.perf_counter() - t) * 1e3)

    def search_batch(self, requests: list) -> list:
        if not requests:
            return []
        lines = []
        for r in requests:
            lines += [json.dumps({"index": self.name}), json.dumps({"track_total_hits": True, **r})]
        t = time.perf_counter()
        resp = _call("POST", "/_msearch", "\n".join(lines) + "\n", ndjson=True)
        ms = (time.perf_counter() - t) * 1e3 / len(requests)
        out = []
        for r in resp["responses"]:
            if "error" in r:
                raise UnsupportedQuery("opensearch", json.dumps(r["error"])[:300])
            out.append(_convert(r, ms))
        return out
